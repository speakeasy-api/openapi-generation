const DEBUG_EXAMPLE_LOGGING = false; // Set this to true to enable very verbose logging of example generation results (don't leave this set to true outside local dev)
const DEBUG_EXAMPLE_OP_FILTER = ""; // Set this to a specific operation ID to only log example results for that operation (don't leave this set outside local dev)
const DEBUG_EXAMPLE_FIELD_FILTER: string = ""; // Set this to a specific field name to only log example results for that field (dot delimited for nested fields) (don't leave this set outside local dev)
const DEBUG_EXAMPLE_NAME_FILTER = ""; // Set this to a specific example name to only log example results for that example name (don't leave this set outside local dev)
const DEBUG_VERBOSE_FIELD_LOGGING = false; //Set this to true to json serialize the entire fieldDef to console
let CURRENT_EXAMPLE_OP_ID = "";
let CURRENT_EXAMPLE_FIELD_NAME_STACK = [];
let CURRENT_EXAMPLE_NAME = "";

function debugExampleLogging(
  message?: string,
  example?: any,
  cachedExample?: any,
  fieldDef?: FieldDef,
) {
  if (shouldDebugExampleLog()) {
    console.log(`[examples] ${message}`);
    if (fieldDef !== undefined) {
      if (DEBUG_VERBOSE_FIELD_LOGGING) {
        console.log("  fieldDef:", JSON.stringify(fieldDef, null, 2));
      } else {
        console.log(
          `  fieldDef - name: ${fieldDef.Name}, type: ${fieldDef.Type.Type}, optional: ${fieldDef.Optional}, nullable: ${fieldDef.Nullable}`,
        );
      }
    }
    console.log("  example:", JSON.stringify(example, null, 2));
    console.log("  cachedExample:", JSON.stringify(cachedExample, null, 2));
  }
}

function setDebugExampleLoggingContext(context: {
  operation?: Operation;
  field?: FieldDef;
  exampleName?: string;
}) {
  CURRENT_EXAMPLE_OP_ID = context.operation?.OriginalID ?? "";

  CURRENT_EXAMPLE_FIELD_NAME_STACK.push(context.field?.Name ?? "");

  CURRENT_EXAMPLE_NAME = context.exampleName ?? "default";

  if (shouldDebugExampleLog()) {
    console.log(
      `[examples] current context - op: ${context.operation
        ?.OriginalID}, field: ${CURRENT_EXAMPLE_FIELD_NAME_STACK.filter(
        (v) => v !== "",
      ).join(".")}, exampleName: ${CURRENT_EXAMPLE_NAME}`,
    );
  }
}

function shouldDebugExampleLog(): boolean {
  return (
    DEBUG_EXAMPLE_LOGGING &&
    (!DEBUG_EXAMPLE_OP_FILTER ||
      CURRENT_EXAMPLE_OP_ID == DEBUG_EXAMPLE_OP_FILTER) &&
    doesDebugFieldMatch() &&
    (!DEBUG_EXAMPLE_NAME_FILTER ||
      CURRENT_EXAMPLE_NAME == DEBUG_EXAMPLE_NAME_FILTER)
  );
}

function doesDebugFieldMatch(): boolean {
  if (!DEBUG_EXAMPLE_FIELD_FILTER) {
    return true;
  }
  const fieldName = CURRENT_EXAMPLE_FIELD_NAME_STACK.filter(
    (v) => v !== "",
  ).join(".");

  if (DEBUG_EXAMPLE_FIELD_FILTER.endsWith("*")) {
    return fieldName.startsWith(DEBUG_EXAMPLE_FIELD_FILTER.slice(0, -1));
  }

  return fieldName === DEBUG_EXAMPLE_FIELD_FILTER;
}

// This directive effectively means use the autogenerated or sub type example
// Used mainly in arrays and maps ie ["...", "..."] or {"someKey": "..."} to control the number of examples
// but not necessarily the exact example used
const UseAutoGeneratedExample = "...";

const examplesHelperInstance = examplesHelper();

/** Additional context for calculating examples. */
type CalculateExampleAdditionalContext = {
  /** Enabled when example being calculated is for a response. */
  isResponse?: boolean;

  /** Enabled when example being calculated is the root of a response schema,
   * which when calculating default test examples should always be included. */
  isResponseSchemaRoot?: boolean;

  /** Enabled when example being calculated should template a default value. */
  templateDefaultValue?: boolean;

  /** Logic to determine if a type's const value should be templated. */
  shouldTemplateConstValue?: (FieldDef, TemplateValueContext) => boolean;

  /** Mapping of TypeDef unique identifiers to the number of times a type as been visited. */
  visited?: Record<string, number>;

  /** Number of sub examples calculated for the given field ID. */
  subExamples?: Map<string, number>;

  /** Enabled when example being calculated is for a test. */
  isTest?: boolean;

  /** The operation being calculated. Generally used for debugging purposes. */
  operation?: Operation;

  /** If the currently generate example is a member of an array, this is the index in that array */
  arrayIdx?: number;

  /** The name of the example being calculated. */
  exampleName?: string;

  /** When true, excludes fields with the json.ignore annotation */
  excludeIgnoredFields?: boolean;

  /** When true the current field is being calculated within a union. Can impact things like whether const values should be templated. */
  withinUnion?: boolean;
};

function preCalculateExamples(
  mainSDK: SDK | null,
  preCalculatedExamples: Examples | null,
): Examples | null {
  if (!mainSDK) {
    return null;
  }

  if (!faker) {
    throw new Error("faker hasn't been injected into runtime");
  }

  if (!preCalculatedExamples) {
    preCalculatedExamples = examplesHelperInstance.NewExamplesMap();
  }

  preCalculateSDKExamples(mainSDK, preCalculatedExamples);

  return preCalculatedExamples;
}

function preCalculateSDKExamples(
  sdk: SDK | null,
  preCalculatedExamples: Examples,
) {
  if (!sdk) {
    return;
  }

  for (const op of sdk.Operations) {
    preCalculateOperationExamples(op, preCalculatedExamples);
  }

  for (const sub of sdk.SubSDKs) {
    preCalculateSDKExamples(sub, preCalculatedExamples);
  }
}

function preCalculateOperationExamples(
  op: Operation | null,
  preCalculatedExamples: Examples,
) {
  if (!op) {
    return;
  }

  const operationSeed = op.GetExampleSeed();
  faker.seed(operationSeed);

  let [opExamples, ok] = preCalculatedExamples.Get(op.OriginalID);
  if (!ok || !opExamples) {
    opExamples = examplesHelperInstance.NewOperationExamplesMap();
  }

  const exampleNames = getAllExampleNamesForOperation(op);

  for (const exampleName of exampleNames) {
    if (op.Request) {
      if (op.Request.RequestBody) {
        let example = getExampleByName(op.Request.Examples, exampleName.name);

        let preCalculatedExample: Example | null = null;
        const [opExample] = opExamples.Get(exampleName.name);

        if (!opExample.RequestBody) {
          opExample.RequestBody = examplesHelperInstance.NewYamlNodeMap();
        }

        if (op.Request?.MatchedContentTypes?.length > 0) {
          // TODO at some point we are likely going to need to match examples with content types instead of just using the first one
          const [exampleNode, ok] = opExample.RequestBody.Get(
            op.Request.MatchedContentTypes[0],
          );
          if (ok) {
            preCalculatedExample = examplesHelperInstance.NewExample(
              exampleName.name,
              exampleNode,
            );
          }
        }

        const additionalContext = {
          operation: op,
          exampleName: exampleName.name,
        };

        const preCalculated = preCalculateExample(
          op.Request.RequestBody,
          example,
          preCalculatedExample,
          additionalContext,
          `preCalculateOperationExamples - RequestBody`,
        );

        if (preCalculated) {
          for (const contentType of op.Request.MatchedContentTypes) {
            opExample.RequestBody.Set(contentType, preCalculated);
          }

          opExamples.Set(exampleName.name, opExample);
        }
      }

      if (op.Request.Params) {
        const calculateParamExample = (
          param: ParamDef,
          paramType: "path" | "query" | "header",
        ) => {
          const example = getExampleByName(param.Examples, exampleName.name);

          let preCalculatedExample: Example | null = null;
          const [opExample] = opExamples.Get(exampleName.name);

          let paramExampleMap: SequencedMap<string, YamlNode> | null = null;

          switch (paramType) {
            case "path":
              if (opExample.Parameters?.Path) {
                paramExampleMap = opExample.Parameters.Path;
              }
              break;
            case "query":
              if (opExample.Parameters?.Query) {
                paramExampleMap = opExample.Parameters.Query;
              }
              break;
            case "header":
              if (opExample.Parameters?.Header) {
                paramExampleMap = opExample.Parameters.Header;
              }
              break;
          }

          if (paramExampleMap) {
            const [exampleNode, ok] = paramExampleMap.Get(
              param.Field.OriginalName,
            );
            if (ok) {
              preCalculatedExample = examplesHelperInstance.NewExample(
                exampleName.name,
                exampleNode,
              );
            }
          }

          const additionalContext = {
            operation: op,
            exampleName: exampleName.name,
          };

          const preCalculated = preCalculateExample(
            param.Field,
            example,
            preCalculatedExample,
            additionalContext,
            `preCalculateOperationExamples - Param ${param.Field.Name}`,
          );

          if (preCalculated) {
            if (!opExample.Parameters) {
              opExample.Parameters =
                examplesHelperInstance.NewParameterExamples();
            }

            if (!paramExampleMap) {
              paramExampleMap = examplesHelperInstance.NewYamlNodeMap();
            }

            paramExampleMap.Set(param.Field.OriginalName, preCalculated);

            switch (paramType) {
              case "path":
                opExample.Parameters.Path = paramExampleMap;
                break;
              case "query":
                opExample.Parameters.Query = paramExampleMap;
                break;
              case "header":
                opExample.Parameters.Header = paramExampleMap;
                break;
            }

            opExamples.Set(exampleName.name, opExample);
          }
        };

        for (const param of op.Request.Params.PathParams) {
          calculateParamExample(param, "path");
        }

        for (const param of op.Request.Params.QueryParams) {
          calculateParamExample(param, "query");
        }

        for (const param of op.Request.Params.HeaderParams) {
          calculateParamExample(param, "header");
        }
      }
    }

    for (const resp of op.Response.Responses) {
      for (const content of resp.Content) {
        const example = getExampleByName(content.Examples, exampleName.name);

        if (
          !example &&
          exampleName.name !==
            examplesHelperInstance.GetDefaultExampleName(op) &&
          exampleName.locations.has("responseBody")
        ) {
          // This isn't the response this example belongs to so we can skip it
          continue;
        }

        let preCalculatedExample: Example | null = null;
        const [opExample] = opExamples.Get(exampleName.name);

        let codeExamples = examplesHelperInstance.NewYamlNodeMap();

        if (resp.Code.length > 0) {
          // TODO at some point we are likely going to need to match with codes instead of just using the first one
          if (opExample.Responses) {
            let [firstCodeExamples, ok] = opExample.Responses.Get(resp.Code[0]);
            if (ok) {
              codeExamples = firstCodeExamples;
            }
          }

          const [exampleNode, okExampleNode] = codeExamples.Get(
            content.ContentType,
          );
          if (okExampleNode) {
            preCalculatedExample = examplesHelperInstance.NewExample(
              exampleName.name,
              exampleNode,
            );
          }
        }

        const additionalContext = {
          isResponse: true,
          isResponseSchemaRoot: true,
          operation: op,
          exampleName: exampleName.name,
        };

        const preCalculated = preCalculateExample(
          content.Content,
          example,
          preCalculatedExample,
          additionalContext,
          `preCalculateOperationExamples - Response ${resp.Code[0]}`,
        );

        if (preCalculated) {
          codeExamples.Set(content.ContentType, preCalculated);

          if (!opExample.Responses) {
            opExample.Responses =
              examplesHelperInstance.NewResponsesExamplesMap();
          }
          let [_, ok] = opExample.Responses.Get(resp.Code[0]);
          if (!ok) {
            opExample.Responses.Set(resp.Code[0], codeExamples);
          }

          opExamples.Set(exampleName.name, opExample);
        }
      }
    }
  }

  preCalculatedExamples.Set(op.OriginalID, opExamples);
}

function preCalculateExample(
  field: FieldDef,
  example: Example,
  preCalculatedExample: Example,
  additionalContext: CalculateExampleAdditionalContext,
  debugMessage: string,
): YamlNode {
  if (!field) {
    throw new Error("field is required");
  }

  setDebugExampleLoggingContext({
    operation: additionalContext.operation,
    field: field,
    exampleName: additionalContext.exampleName,
  });

  let rawExample = undefined;
  if (example) {
    rawExample = getExampleValue(example);
  }

  let rawPreCalculatedExample = undefined;
  if (preCalculatedExample) {
    rawPreCalculatedExample = getExampleValue(preCalculatedExample);
  }

  debugExampleLogging(debugMessage, rawExample, rawPreCalculatedExample, field);

  const calculatedExample = calculateExample(
    field,
    rawExample,
    rawPreCalculatedExample,
    false,
    additionalContext,
    false,
  );

  if (calculatedExample === undefined || calculatedExample === TRUNCATED) {
    return undefined;
  }

  return examplesHelperInstance.YamlNodeFromString(
    JSON.stringify(calculatedExample),
  );
}

const TRUNCATED = Symbol("TRUNCATED");

function calculateExample(
  fieldDef: FieldDef,
  // example generally holds the raw json based example retrieved from the customers spec or provided via an arazzo dock
  example: any | undefined,
  // cachedExample generally holds the pre-calculated example from the gen.lock and is used whenever the example from the spec is incorrect or not suitable for the type it is being associated with
  // this avoids constant churn of examples as if an example is unusable we would normally generate a new one that then gets saved to the gen.lock
  cachedExample: any | undefined,
  // When checking if a field should be included it is important to know if the field is a child of an object with an example
  // because if there isn't an example for this field in the parent object then it likely was purposefully excluded if it was optional and we shouldn't generate an example for it
  parentHasExample: boolean,
  additionalContext: CalculateExampleAdditionalContext,
  setDebugContext = true,
): any {
  const typeDef = fieldDef.Type;

  if (setDebugContext) {
    setDebugExampleLoggingContext({
      operation: additionalContext.operation,
      field: fieldDef,
      exampleName: additionalContext.exampleName,
    });
  }

  debugExampleLogging(
    `calculateExample - start: parentHasExample: ${parentHasExample}`,
    example,
    cachedExample,
    fieldDef,
  );

  const calculate = () => {
    ///////////////////////////////////////////////////////////
    // Handle circular references
    if (additionalContext.visited === undefined) {
      additionalContext.visited = {};
      additionalContext.subExamples = new Map<string, number>();
    }

    if (typeDef.IsCustomType()) {
      const VISITS_ALLOWED = 2; // We allow a depth of two circular references when generating examples to not hamstring examples too much
      const visitedCount = additionalContext.visited[getUniqueID(typeDef)] ?? 0;

      // Check if we are trapped in a circular ref generating examples and early exit if so
      // but if an example is provided, we will continue as we are just being guided by the examples in the spec
      if (
        typeDef.Truncated ||
        (visitedCount >= VISITS_ALLOWED && example === undefined)
      ) {
        debugExampleLogging(
          `skipping example generation for ${typeDef.Name} as it is a circular reference`,
          undefined,
          undefined,
          fieldDef,
        );

        return fieldDef.Optional ? undefined : TRUNCATED;
      }

      additionalContext.visited[getUniqueID(typeDef)] = visitedCount + 1;
    }

    ///////////////////////////////////////////////////////////
    // Check if the field should just be omitted from the generated example, for example if its an optional field with no example and the config allows that
    if (
      !shouldIncludeField(fieldDef, example, parentHasExample, {
        ...additionalContext,
        templateDefaultValue: true,
        shouldTemplateConstValue:
          additionalContext?.shouldTemplateConstValue || (() => true),
        excludeIgnoredFields: true,
      }) &&
      !additionalContext.isResponseSchemaRoot // Always allow examples for responses otherwise we get no examples generated in some cases
    ) {
      debugExampleLogging(
        "calculateExample - should not include field",
        example,
        cachedExample,
        fieldDef,
      );

      return undefined;
    }

    // If we receive the special value "UseAutoGeneratedExample" then we want to generate an example for this field, so setting example to undefined will cause the example to be generated
    if (example === UseAutoGeneratedExample) {
      example = undefined;
    }

    // If the example is null and it isn't a nullable field then we need to generate an example
    if (example === null && !fieldDef.Nullable) {
      example = undefined;
    }

    // If we have a const value always use this as nothing else is valid
    if (fieldDef.Const) {
      example = fieldDef.Const.Value;
    }

    // If we have no example try to find a source
    if (example === undefined) {
      if (typeDef.Examples?.length > 0) {
        // Try each example until we find one that can be resolved (some may have references that require test context)
        for (const ex of typeDef.Examples) {
          const value = getExampleValue(ex);
          if (value !== undefined) {
            example = value;
            break;
          }
        }
      }
      if (example === undefined && fieldDef.Default) {
        example = fieldDef.Default.Value; // Use the default value if available and no examples are available
      } else if (
        cachedExample !== undefined &&
        (!typeDef.IsCustomClass() || cachedExample === null)
      ) {
        // Use the cached example if we have already generated one for non-class types. (Class types have special handling for non-null cached examples so don't use cached example yet)
        example = cachedExample;
        cachedExample = undefined; // Clear the cached example
      }
    }

    // If the example is still null for a non-nullable field (set incorrectly to null somewhere above) then just regenerate it
    if (example === null && !fieldDef.Nullable) {
      example = undefined;
    }

    // If the field is nullable check if the example is null and just return that
    // otherwise roll the dice on whether to return null or generate an example
    if (fieldDef.Nullable) {
      if (example === null) {
        return null;
      }
      // 10% chance of returning null if we have no example and no cached example
      if (example === undefined && cachedExample === undefined) {
        if (faker.datatype.boolean(0.1)) {
          return null;
        }
      }
    }

    debugExampleLogging(
      "calculateExample - resolved",
      example,
      cachedExample,
      fieldDef,
    );

    if (isMultipartFileField(fieldDef) || fieldDef.Type.IsMultipartFile) {
      return calculateMultipartFileExample(
        fieldDef,
        example,
        cachedExample,
        additionalContext,
      );
    }

    const arrayIdx = additionalContext.arrayIdx;
    delete additionalContext.arrayIdx;

    switch (typeDef.Type.toString()) {
      case "union":
        const { type: typeToUse, example: selectedExample } =
          selectExampleUnionType(
            fieldDef,
            example,
            cachedExample,
            additionalContext,
          );

        if (fieldDef.Nullable && selectedExample === null) {
          return selectedExample;
        }

        const outExample = calculateExample(
          typeDefToFieldDef(typeToUse, fieldDef),
          selectedExample,
          cachedExample,
          false,
          {
            ...(additionalContext ?? {}),
            withinUnion: true,
            templateDefaultValue: true,
          },
        );

        return outExample;
      case "error":
      case "class":
        return calculateObjectExample(
          fieldDef,
          example,
          cachedExample,
          additionalContext,
        );
      case "enum":
        return calculateEnumExample(
          fieldDef,
          example,
          cachedExample,
          additionalContext,
        );
      case "array":
      case "set":
        return calculateArraySetExample(
          fieldDef,
          example,
          cachedExample,
          additionalContext,
        );
      case "map":
        return calculateMapExample(
          fieldDef,
          example,
          cachedExample,
          additionalContext,
        );
      case "any":
        return calculateAnyExample(fieldDef, example, cachedExample, {
          ...additionalContext,
          arrayIdx,
        });
      case "request-stream":
      case "response-stream":
        return calculateStreamExample(
          fieldDef,
          example,
          cachedExample,
          additionalContext,
        );
      case "event-stream":
      case "request":
      case "response":
      case "jsonl":
        return example; // TODO do we need to provide an example if unset
      default:
        return calculateBasicExample(fieldDef, example, cachedExample, {
          ...additionalContext,
          arrayIdx,
        });
    }
  };

  const calculated = calculate();

  debugExampleLogging(
    `calculateExample - calculated`,
    calculated,
    undefined,
    fieldDef,
  );

  CURRENT_EXAMPLE_FIELD_NAME_STACK.pop();

  return calculated;
}

const examplesCache = new Map<string, any>();
function calculateObjectExample(
  fieldDef: FieldDef,
  example: any | undefined,
  cachedExample: any | undefined,
  additionalContext: CalculateExampleAdditionalContext,
): any {
  if (example !== undefined) {
    return calculateObjectExampleInner(
      fieldDef,
      example,
      cachedExample,
      additionalContext,
    );
  }

  const cacheID =
    (additionalContext.operation?.OriginalID ?? "") + fieldDef.GetID();

  if (examplesCache.has(cacheID)) {
    return examplesCache.get(cacheID);
  }

  const result = calculateObjectExampleInner(
    fieldDef,
    example,
    cachedExample,
    additionalContext,
  );
  if (cacheID) examplesCache.set(cacheID, result);
  return result;
}

function calculateObjectExampleInner(
  fieldDef: FieldDef,
  example: any | undefined,
  cachedExample: any | undefined,
  additionalContext: CalculateExampleAdditionalContext,
): any {
  const typeDef = fieldDef.Type;

  let outExample = {};

  let remainingExample = undefined;
  let remainingCachedExample = undefined;

  let exampleProvided = true;

  if (example !== undefined) {
    if (typeof example === "string" && example.startsWith("{")) {
      try {
        example = JSON.parse(example);
      } catch {
        example = undefined;
      }
    }

    if (
      typeof example !== "object" ||
      Array.isArray(example) ||
      example === null
    ) {
      example = undefined;
    }
  }

  if (example === undefined) {
    exampleProvided = false;
    example = {}; // Set to empty object
  }

  remainingExample = { ...example };
  if (cachedExample !== undefined) {
    remainingCachedExample = { ...cachedExample };
  }

  let additionalPropertiesField: FieldDef | undefined = undefined;

  for (const field of typeDef.Fields) {
    if (field.IsAdditionalProperties) {
      additionalPropertiesField = field;
      continue;
    }

    let fieldExample = remainingExample?.[field.OriginalName];
    let fieldCachedExample = remainingCachedExample?.[field.OriginalName];
    delete remainingExample?.[field.OriginalName];
    delete remainingCachedExample?.[field.OriginalName];

    fieldExample = calculateExample(
      field,
      fieldExample,
      fieldCachedExample,
      exampleProvided,
      {
        ...additionalContext,
        isResponseSchemaRoot: false,
        visited: { ...additionalContext.visited },
      },
    );

    if (fieldExample === TRUNCATED) {
      if (!field.Optional) {
        return fieldDef.Optional ? undefined : TRUNCATED;
      }

      fieldExample = undefined;
    }

    if (fieldExample !== undefined) {
      outExample[field.OriginalName] = fieldExample;
    }
  }

  if (additionalPropertiesField !== undefined) {
    let additionalPropertiesExample = calculateExample(
      additionalPropertiesField,
      remainingExample,
      remainingCachedExample,
      false,
      { ...additionalContext, visited: { ...additionalContext.visited } },
    );

    if (
      additionalPropertiesExample !== undefined &&
      additionalPropertiesExample !== TRUNCATED
    ) {
      outExample = { ...outExample, ...additionalPropertiesExample };
    }
  }

  return outExample;
}

function calculateEnumExample(
  fieldDef: FieldDef,
  example: any | undefined,
  cachedExample: any | undefined,
  _additionalContext?: CalculateExampleAdditionalContext,
) {
  const typeDef = fieldDef.Type;

  let exampleIdx = -1;
  if (example !== undefined) {
    exampleIdx = typeDef.Enum.Values.indexOf(`${example}`);

    // If we didn't find a value use the cached example if available to avoid churn
    if (exampleIdx == -1 && cachedExample !== undefined) {
      exampleIdx = typeDef.Enum.Values.indexOf(`${cachedExample}`);
    }
  }

  if (exampleIdx == -1) {
    exampleIdx = faker.number.int(typeDef.Enum.Values.length - 1);
  }

  switch (typeDef.Enum.Type.Type.toString()) {
    case "integer":
    case "int32":
      return parseInt(typeDef.Enum.Values[exampleIdx]);
    default:
      return typeDef.Enum.Values[exampleIdx];
  }
}

function calculateArraySetExample(
  fieldDef: FieldDef,
  example: any | undefined,
  cachedExample: any | undefined,
  additionalContext: CalculateExampleAdditionalContext,
): any {
  const typeDef = fieldDef.Type;

  const fieldID = fieldDef.Type.ItemType?.IsCustomType()
    ? fieldDef.GetID()
    : "";

  const count = additionalContext.subExamples.get(fieldID) || 0;

  // Prevent massive examples from being generated by short circuiting
  if (count > 0 && isPartOfCycle(typeDef) && example === undefined) {
    return fieldDef.Optional ? undefined : [];
  }

  if (fieldID) additionalContext.subExamples.set(fieldID, count + 1);

  if (example === undefined) {
    if (typeDef.ItemType.Examples?.length > 0) {
      example = getExamplesArray(typeDef.ItemType.Examples); // Use any item schema level examples if no example is provided
    } else {
      const min = fieldDef.Optional ? 1 : 0;
      const max = fieldDef.Type.ItemType?.IsCustomType() ? 1 : 3; // If the item type is a custom type we only generate one example as it might be large, otherwise we generate up to 3

      // Generate a random example
      example = [];
      const numExamples = faker.number.int({
        min: min,
        max: max,
      });
      for (let i = 0; i < numExamples; i++) {
        example.push(UseAutoGeneratedExample);
      }
    }
  }

  if (example !== undefined) {
    // If the example is a string then try to parse it as an array
    if (typeof example === "string" && example.startsWith("[")) {
      try {
        example = JSON.parse(example);
      } catch {}
    }

    // It is a common mistake to declare the example as scalar value so just convert it to an array
    if (!Array.isArray(example)) {
      example = [example];
    }
  }

  const outExample = [];

  for (let idx = 0; idx < example.length; idx++) {
    const ex = example[idx];
    const preCalculatedEx = cachedExample?.[idx];

    const itemExample = calculateExample(
      typeDefToFieldDef(typeDef.ItemType, fieldDef),
      ex,
      preCalculatedEx,
      false,
      {
        ...additionalContext,
        isResponseSchemaRoot: false,
        visited: { ...additionalContext.visited },
        arrayIdx: idx,
      },
    );

    if (itemExample !== undefined && itemExample !== TRUNCATED) {
      outExample.push(itemExample);
    }
  }

  return outExample;
}

// @ts-ignore
function calculateMapExample(
  fieldDef: FieldDef,
  example: any | undefined,
  cachedExample: any | undefined,
  additionalContext: CalculateExampleAdditionalContext,
): any {
  const typeDef = fieldDef.Type;

  const fieldID = fieldDef.Type?.IsCustomType() ? fieldDef.GetID() : "";

  const count = additionalContext.subExamples.get(fieldID) || 0;

  // Prevent massive examples from being generated by short circuiting
  if (count > 0 && isPartOfCycle(typeDef) && example === undefined) {
    return fieldDef.Optional ? undefined : {};
  }

  if (fieldID) additionalContext.subExamples.set(fieldID, count + 1);

  if (example !== undefined) {
    if (typeof example === "string" && example.startsWith("{")) {
      try {
        example = JSON.parse(example);
      } catch {
        example = undefined;
      }
    }

    // If the example isn't an object use the cachedExample
    if (typeof example !== "object") {
      if (cachedExample !== undefined) {
        example = cachedExample;
        cachedExample = undefined;
      } else {
        example = undefined;
      }
    }
  }

  // If we have no example just generate a random one
  if (example === undefined) {
    const min = fieldDef.Optional ? 1 : 0;
    const max = fieldDef.Type.ItemType?.IsCustomType() ? 1 : 3; // If the item type is a custom type we only generate one example as it might be large, otherwise we generate up to 3

    const numExamples = faker.number.int({
      min: min,
      max: max,
    });
    example = {};
    for (let i = 0; i < numExamples; i++) {
      example[templatePlaceholderMapKeyValue(i)] = UseAutoGeneratedExample;
    }
  }

  const outExample = {};

  for (const key in example) {
    const itemExample = calculateExample(
      typeDefToFieldDef(typeDef.ItemType, fieldDef),
      example[key],
      cachedExample?.[key],
      false,
      {
        ...additionalContext,
        isResponseSchemaRoot: false,
        visited: { ...additionalContext.visited },
      },
    );

    if (itemExample !== undefined && itemExample !== TRUNCATED) {
      outExample[key] = itemExample;
    }
  }

  return outExample;
}

function calculateAnyExample(
  fieldDef: FieldDef,
  example: any | undefined,
  cachedExample: any | undefined,
  additionalContext: CalculateExampleAdditionalContext,
): any {
  const typeDef = fieldDef.Type;

  const arrayIdx = additionalContext.arrayIdx;
  delete additionalContext.arrayIdx;

  if (typeDef.AssociatedTypes?.length > 0) {
    if (example !== undefined) {
      let subType = matchTypeWithExample(typeDef, example)?.type;

      // Try with the cachedExample instead
      if (!subType && cachedExample !== undefined) {
        subType = matchTypeWithExample(typeDef, cachedExample)?.type;
        if (subType) {
          example = cachedExample;
        }
      }

      if (subType && subType != typeDef) {
        return calculateExample(
          typeDefToFieldDef(subType, fieldDef),
          example,
          cachedExample,
          false,
          {
            ...(additionalContext ?? {}),
            withinUnion: true,
            templateDefaultValue: true,
          },
        );
      }
    }

    return calculateExample(
      typeDefToFieldDef(
        faker.helpers.arrayElement(typeDef.AssociatedTypes),
        fieldDef,
      ),
      undefined,
      undefined,
      false,
      additionalContext,
    );
  }

  return calculateBasicExample(fieldDef, example, cachedExample, {
    ...additionalContext,
    arrayIdx,
  });
}

function calculateBasicExample(
  fieldDef: FieldDef,
  example: any | undefined,
  cachedExample: any | undefined,
  additionalContext: CalculateExampleAdditionalContext,
): any {
  const fieldName = fieldDef.Name
    ? caser().ToSnake(fieldDef.Name).replaceAll("_", "").toLowerCase()
    : undefined;

  const typeDef = fieldDef.Type;

  const getStringExample = (arrayIdx?: number) => {
    // If the example isn't a string lets try to convert it to one
    if (example !== undefined && typeof example != "string") {
      try {
        return JSON.stringify(example);
      } catch {
        if (cachedExample !== undefined) {
          example = cachedExample; // Use the cached example if we have already generated one
          cachedExample = undefined;
        } else {
          example = undefined; // Generate a random example
        }
      }
    }

    if (example === undefined) {
      if (typeDef.Format) {
        example = fakeString(typeDef.Format.toString(), arrayIdx);
      } else if (fieldName !== undefined) {
        example = fakeString(fieldName, arrayIdx);
      } else {
        example = templatePlaceholderString(arrayIdx);
      }
    }

    return example;
  };

  switch (typeDef.Type.toString()) {
    case "string":
      return getStringExample(additionalContext.arrayIdx);
    case "int32":
    case "bigint":
    case "integer": {
      if (typeDef.Format != "string" && typeof example != "number") {
        let useCachedOrUndefined = false;

        // If the example is a string then try to parse it as an int
        if (typeof example == "string") {
          try {
            example = parseInt(example);
          } catch {
            useCachedOrUndefined = true;
          }
        }

        if (useCachedOrUndefined) {
          if (cachedExample !== undefined) {
            example = cachedExample; // Use the cached example if we have already generated one
            cachedExample = undefined;
          } else {
            example = undefined; // Generate a random example
          }
        }
      }

      const outExample =
        example !== undefined ? example : faker.number.int(1000000);

      return typeDef.Format == "string" ? `${outExample}` : outExample;
    }
    case "float32":
    case "decimal":
    case "number": {
      if (typeDef.Format != "string" && typeof example != "number") {
        let useCachedOrUndefined = false;

        // If the example is a string then try to parse it as an float
        if (typeof example == "string") {
          try {
            example = parseFloat(example);
          } catch {
            useCachedOrUndefined = true;
          }
        }

        if (useCachedOrUndefined) {
          if (cachedExample !== undefined) {
            example = cachedExample; // Use the cached example if we have already generated one
            cachedExample = undefined;
          } else {
            example = undefined; // Generate a random example
          }
        }
      }

      const outExample =
        example !== undefined
          ? example
          : faker.number.float({ min: 0, max: 10000, fractionDigits: 2 });

      return typeDef.Format == "string" ? `${outExample}` : outExample;
    }
    case "boolean":
      if (typeof example != "boolean") {
        if (cachedExample !== undefined) {
          example = cachedExample; // Use the cached example if we have already generated one
          cachedExample = undefined;
        } else {
          example = undefined; // Generate a random example
        }
      }

      return example !== undefined ? example : faker.datatype.boolean();
    case "date":
      if (typeof example != "string") {
        if (cachedExample !== undefined) {
          example = cachedExample; // Use the cached example if we have already generated one
          cachedExample = undefined;
        } else {
          example = undefined; // Generate a random example
        }
      }

      return example !== undefined ? example : fakeDateTime().split("T")[0];
    case "date-time":
      if (typeof example != "string") {
        if (cachedExample !== undefined) {
          example = cachedExample; // Use the cached example if we have already generated one
          cachedExample = undefined;
        } else {
          example = undefined; // Generate a random example
        }
      }

      return example !== undefined ? example : fakeDateTime();
    case "uuid":
      if (typeof example != "string") {
        if (cachedExample !== undefined) {
          example = cachedExample; // Use the cached example if we have already generated one
          cachedExample = undefined;
        } else {
          example = undefined; // Generate a random example
        }
      }

      return example !== undefined ? example : faker.string.uuid();
    case "duration":
      if (typeof example != "string") {
        if (cachedExample !== undefined) {
          example = cachedExample; // Use the cached example if we have already generated one
          cachedExample = undefined;
        } else {
          example = undefined; // Generate a random example
        }
      }

      return example !== undefined ? example : "PT1H";
    case "bytes":
      if (example !== undefined && typeof example != "string") {
        example = JSON.stringify(example);
      }

      return example !== undefined
        ? example
        : faker.string.hexadecimal({
            length: 10,
          });
    case "any":
      if (example === undefined) {
        return getStringExample(additionalContext.arrayIdx);
      }

      return example;
    default:
      throw new Error(`invalid type ${typeDef.Type.toString()}`);
  }
}

