function getExampleValue(
  example: Example,
  additionalContext?: TemplateValueContext,
): any | ExampleReferenceValue {
  if (!example) {
    return undefined;
  }

  // The example is possible already resolved so just return it
  if (!("ToJSON" in example)) {
    return example;
  }

  const testContext = getTestContext(additionalContext);

  if (example.Reference) {
    if (!testContext) {
      // Return undefined when there's no test context to resolve a reference.
      // This allows the rendering pipeline to fall back to generated/default values.
      return undefined;
    }

    switch (example.Reference.Type) {
      case "response.body": {
        const target = example.Reference.Target as ResponseBodyTarget;

        const steps = testContext.Steps;

        if (!steps || target.StepIdx < 0 || target.StepIdx >= steps.length) {
          throw new Error(
            `example reference target step index ${target.StepIdx} is out of bounds of steps in test`,
          );
        }

        let basePath = "";

        const step = steps[target.StepIdx];

        switch (step.Type) {
          case "operation":
            const stepUsageContext = step.UsageContext;

            basePath = getResponseContentVariablePath(
              stepUsageContext,
              target.Body,
            );
            break;
          case "workflow":
            basePath = getOutputVariableName(step.StepID, true);
            break;
          default:
            throw new Error(
              `example reference target step index ${target.StepIdx} is not an operation or workflow`,
            );
        }

        let parents: FieldDef[] = [];

        const path = templateJSONPointerPath(
          target.Body?.Content,
          basePath,
          target.Path,
          (partIdx, parent: FieldDef, currentPath) => {
            parents.push(parent);
          },
          additionalContext,
        );

        const exampleReferenceValue: ExampleReferenceValue = {
          isExampleReferenceValue: true,
          path: path.path,
          parents: parents,
          source: getTargetAsFieldDef(target.Target),
          replacements: example.Replacements,
        };

        return exampleReferenceValue;
      }
      case "inputs": {
        const target = example.Reference.Target as InputTarget;

        let parents: FieldDef[] = [];

        const path = templateJSONPointerPath(
          target.Inputs,
          "inputs",
          target.Path,
          (partIdx, parent: FieldDef, currentPath) => {
            parents.push(parent);
          },
          additionalContext,
        );

        return {
          isExampleReferenceValue: true,
          path: path.path,
          parents: parents,
          source: getTargetAsFieldDef(target.Target),
          replacements: example.Replacements,
        };
      }
      case "outputs": {
        const target = example.Reference.Target as OutputTarget;

        const steps = testContext.Steps;

        if (!steps || target.StepIdx < 0 || target.StepIdx >= steps.length) {
          throw new Error(
            `example reference target step index ${target.StepIdx} is out of bounds of steps in test`,
          );
        }

        let parents: FieldDef[] = [];

        const path = templateJSONPointerPath(
          target.Outputs,
          getOutputVariableName(steps[target.StepIdx].StepID, true),
          target.Path,
          (partIdx, parent: FieldDef, currentPath) => {
            parents.push(parent);
          },
          additionalContext,
        );

        return {
          isExampleReferenceValue: true,
          path: path.path,
          parents: parents,
          source: getTargetAsFieldDef(target.Target),
          replacements: example.Replacements,
        };
      }
      default:
        throw new Error(
          `unsupported example reference type: ${
            (example.Reference as any).Type
          }`,
        );
    }
  }

  try {
    const value = JSON.parse(example.ToJSON());

    for (const replacement of example.Replacements ?? []) {
      jsonpointer.set(
        value,
        replacement.Path,
        getExampleValue(replacement.Value, additionalContext),
      );
    }

    return value;
  } catch (e) {
    throw new Error(
      `Failed to parse example value ${example.ToJSON()}: ${
        e instanceof Error ? e.message : e
      }`,
    );
  }
}

