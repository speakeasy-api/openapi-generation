function selectExampleUnionType(
  fieldDef: FieldDef,
  example: any,
  cachedExample: any,
  additionalContext?: CalculateExampleAdditionalContext,
): { type: TypeDef; example: any } {
  const typeDef = fieldDef.Type;

  const types = typeDef.Discriminator
    ? typeDef.Discriminator.Mapping.map((m) => m.Type)
    : typeDef.AssociatedTypes;

  if (types.length == 0) {
    // TODO: this is not likely to work we will prob need a special case return for this
    return { type: typeDef, example: undefined };
  }

  let typeToUse: TypeDef = undefined;

  if (example === undefined) {
    // If we have no example grab the first defined example on the associated types
    for (const type of types) {
      if (type.Examples.length > 0) {
        example = getExampleValue(type.Examples[0]);
        break;
      }
    }

    // If we still don't have an example use the cached example
    if (example === undefined && cachedExample !== undefined) {
      example = cachedExample;
      cachedExample = undefined;
    }
  }

  if (example !== undefined) {
    // If the example contains a string like "anyOf[0]" then we can use that to select the type referenced by the index
    const matches =
      typeof example === "string"
        ? example.match(/(?:anyOf|oneOf)\[(\d+)\]/)
        : undefined;

    if (matches && matches.length > 1) {
      typeToUse = types[parseInt(matches[1])];
      example = UseAutoGeneratedExample;
    } else {
      // Else we try and match the example to one of the types
      const res = matchTypeWithExample(typeDef, example, additionalContext);
      if (res) {
        typeToUse = res.type;
      }
    }
  }

  // If we had an example but it didn't match then try and use the cached example from gen.lock to avoid churn
  if (!typeToUse && example !== undefined && cachedExample !== undefined) {
    debugExampleLogging(
      `selectExampleUnionType - no match found for example so trying to use cached example`,
      example,
      cachedExample,
    );

    // If the cached example is null and the field is nullable then we will just use the first type and continue to use the null example
    if (fieldDef.Nullable && cachedExample === null) {
      return { type: types[0], example: null };
    }

    const {
      type: typeToUseFromPreCalculatedExample,
      example: exampleFromPreCalculatedExample,
    } = selectExampleUnionType(
      fieldDef,
      cachedExample,
      undefined,
      additionalContext,
    );
    typeToUse = typeToUseFromPreCalculatedExample;
    example = exampleFromPreCalculatedExample;
  }
  if (!typeToUse) {
    const idxToUse = faker.number.int(types.length - 1);
    typeToUse = types[idxToUse];

    if (typeDef.Discriminator) {
      // We need to partially construct the object here to make sure we use the correct discriminator value
      const typeDiscriminator = typeDef.Discriminator.Mapping[idxToUse].Name;
      example = {
        [typeDef.Discriminator.TypePropertyName]: typeDiscriminator,
      };
    } else {
      example = UseAutoGeneratedExample;
    }

    debugExampleLogging(
      `selectExampleUnionType - no match found for example or cached example so using a random type from the list ${typeToUse.Name} - ${typeToUse.Type}`,
      example,
      cachedExample,
    );
  }

  return { type: typeToUse, example };
}

function shouldTemplateFieldConstValue(
  field: FieldDef,
  additionalContext?: CalculateExampleAdditionalContext,
): boolean {
  // Strict compare against false so that falsy (i.e.`undefined`) values don't trigger this branch
  if (context.Global.Config.ConstFieldsAlwaysOptional === false) {
    return (
      !field.Optional ||
      additionalContext?.shouldTemplateConstValue?.(field, additionalContext) ||
      false
    );
  } else {
    return (
      additionalContext?.shouldTemplateConstValue?.(field, additionalContext) ||
      false
    );
  }
}

type ExampleNameLocation = "requestBody" | "responseBody" | "parameter";

type ExampleName = {
  name: string;
  locations: Set<ExampleNameLocation>;
};

function getAllExampleNamesForOperation(op: Operation): ExampleName[] {
  const exampleNames: ExampleName[] = [];

  const collectExampleNames = (
    examples: Example[] | undefined,
    location: ExampleNameLocation,
  ): boolean => {
    let foundAny = false;
    for (const example of examples ?? []) {
      let name = example.Name();

      if (!example.Value) {
        continue;
      }

      foundAny = true;

      if (name === "") {
        name = examplesHelperInstance.GetDefaultExampleName(op);
      }

      let found = false;

      for (let i = 0; i < exampleNames.length; i++) {
        const ex = exampleNames[i];
        if (ex.name === name) {
          exampleNames[i].locations.add(location);
          found = true;
          break;
        }
      }

      if (!found) {
        exampleNames.push({
          name: name,
          locations: new Set([location]),
        });
      }
    }
    return foundAny;
  };

  let hasRequestBody = false;
  let hasParameters = false;

  if (op.Request) {
    if (op.Request.RequestBody) {
      hasRequestBody = true;
      collectExampleNames(op.Request.Examples, "requestBody");
    }

    if (op.Request.Params) {
      for (const param of op.Request.Params.PathParams) {
        hasParameters = true;
        collectExampleNames(param.Examples, "parameter");
      }

      for (const param of op.Request.Params.QueryParams) {
        hasParameters = true;
        collectExampleNames(param.Examples, "parameter");
      }

      for (const param of op.Request.Params.HeaderParams) {
        hasParameters = true;
        collectExampleNames(param.Examples, "parameter");
      }
    }
  }

  // Track whether we found examples on success responses (2xx or 3xx as fallback)
  let hasSuccessResponseExample = false;
  let has2xxResponse = false;
  let has3xxResponseExample = false;

  for (const resp of op.Response.Responses) {
    const is2xx = resp.Code.some((c) => c.startsWith("2"));
    const is3xx = resp.Code.some((c) => c.startsWith("3"));

    if (is2xx) {
      has2xxResponse = true;
    }

    for (const content of resp.Content) {
      const foundExamples = collectExampleNames(
        content.Examples,
        "responseBody",
      );

      if (foundExamples) {
        if (is2xx) {
          hasSuccessResponseExample = true;
        } else if (is3xx) {
          has3xxResponseExample = true;
        }
      }
    }
  }

  // If no 2xx responses exist, treat 3xx as success
  if (!has2xxResponse && has3xxResponseExample) {
    hasSuccessResponseExample = true;
  }

  if (exampleNames.length === 0) {
    const locations: Set<ExampleNameLocation> = new Set(["responseBody"]);

    if (hasRequestBody) {
      locations.add("requestBody");
    }

    if (hasParameters) {
      locations.add("parameter");
    }

    exampleNames.push({
      name: examplesHelperInstance.GetDefaultExampleName(op),
      locations: locations,
    });
  } else if (!hasSuccessResponseExample) {
    // We have examples but none cover success responses, add the default
    // example to ensure success responses get examples generated
    const defaultExampleName = examplesHelperInstance.GetDefaultExampleName(op);

    // Check if default example name already exists
    let defaultExists = false;
    for (const ex of exampleNames) {
      if (ex.name === defaultExampleName) {
        // Ensure responseBody is in the locations
        ex.locations.add("responseBody");
        if (hasRequestBody) {
          ex.locations.add("requestBody");
        }
        if (hasParameters) {
          ex.locations.add("parameter");
        }
        defaultExists = true;
        break;
      }
    }

    if (!defaultExists) {
      const locations: Set<ExampleNameLocation> = new Set(["responseBody"]);

      if (hasRequestBody) {
        locations.add("requestBody");
      }

      if (hasParameters) {
        locations.add("parameter");
      }

      exampleNames.push({
        name: defaultExampleName,
        locations: locations,
      });
    }
  }

  return exampleNames;
}

function getExampleByName(examples: Example[], name: string): Example | null {
  for (const example of examples) {
    if (example.Name() === name) {
      return example;
    }
  }
  return null;
}

