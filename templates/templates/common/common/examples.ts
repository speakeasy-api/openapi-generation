function shouldIncludeField(
  fieldDef: FieldDef,
  example: any | undefined,
  parentHasExample?: boolean,
  additionalContext?: CalculateExampleAdditionalContext,
): boolean {
  if (additionalContext?.excludeIgnoredFields) {
    const jsonAnno = fieldDef.Annotations?.Get("json");
    if (jsonAnno?.Ignore && !fieldDef.IsAdditionalProperties) {
      debugExampleLogging(
        `field ${fieldDef.Name} is marked as ignored and will not be included`,
        example,
        undefined,
        fieldDef,
      );

      return false;
    }
  }

  const paramAnno = fieldDef.Annotations?.Get("param");
  if (paramAnno) {
    if (fieldDef.Optional && paramAnno.RequiredForOperation) {
      return true;
    }
  }

  return includeField(fieldDef, example, parentHasExample, additionalContext);
}

// @ts-ignore
function includeField(
  field: FieldDef,
  example?: any,
  parentHasExample?: boolean,
  additionalContext?: CalculateExampleAdditionalContext,
): boolean {
  // We specifically want to generate an example so include field
  if (example === UseAutoGeneratedExample) {
    return true;
  }

  if (field.Const) {
    const templateConstValue = shouldTemplateFieldConstValue(
      field,
      additionalContext,
    );

    return templateConstValue;
  }

  if (!field.Optional) {
    return true;
  }

  if (field.Default) {
    const templateDefaultValue =
      additionalContext?.templateDefaultValue ?? false;

    debugExampleLogging(
      `field ${field.Name} has a default value and will ${
        templateDefaultValue ? "" : "not"
      } be included`,
      example,
      undefined,
      field,
    );

    return additionalContext?.templateDefaultValue ?? false;
  }

  const renderProp = renderProperty(
    field,
    example,
    parentHasExample,
    additionalContext,
  );
  if (!renderProp) {
    debugExampleLogging(
      `field ${field.Name} will not be included as it is not renderable`,
      example,
      undefined,
      field,
    );
    return false;
  }

  if (field.Comments?.Deprecated && example === undefined) {
    debugExampleLogging(
      `field ${field.Name} is deprecated and will not be included due to missing example`,
      example,
      undefined,
      field,
    );
    return false;
  }

  return true;
}

function renderProperty(
  field: FieldDef,
  example: any | undefined,
  parentHasExample?: boolean,
  additionalContext?: CalculateExampleAdditionalContext,
): boolean {
  let optionalPropertyRendering =
    context.Global.Config["OptionalPropertyRendering"];

  if (additionalContext?.isTest) {
    // If we are in a test and a test value is provided we will always render it regardless of the config
    optionalPropertyRendering = "withExample";
  }

  switch (optionalPropertyRendering) {
    case "always":
      return true;
    case "never":
      return false;
    case "withExample":
      // If we have an example value, we always render it
      if (example !== undefined) {
        return true;
      }
      // If our parent didn't included an example that excluded us and we have schema level examples, we render
      if (!parentHasExample && typeHasExamples(field.Type)) {
        return true;
      }

      // Otherwise don't render optional property
      return false;
  }
}

const typeHasExamplesCache = new Map<string, boolean>();
function typeHasExamples(
  type: TypeDef,
  visited: Record<string, boolean> = {},
): boolean {
  const id = type.IsCustomType() ? getUniqueID(type) : "";
  if (typeHasExamplesCache.has(id)) {
    return typeHasExamplesCache.get(id);
  }
  const ret = typeHasExamplesInner(type, visited);
  if (id) typeHasExamplesCache.set(id, ret);
  return ret;
}

function typeHasExamplesInner(
  type: TypeDef,
  visited: Record<string, boolean> = {},
): boolean {
  if (type.IsCustomType()) {
    if (type.Truncated || visited[getUniqueID(type)]) {
      return false;
    }

    visited[getUniqueID(type)] = true;
  }

  if (type.Examples.length > 0) {
    return true;
  }

  switch (type.Type.toString()) {
    case "error":
    case "class":
      return type.Fields.some((f) => typeHasExamples(f.Type, visited));
    case "union":
      return type.AssociatedTypes.some((t) => typeHasExamples(t, visited));
    case "map":
    case "array":
    case "set":
      return typeHasExamples(type.ItemType, visited);
    default:
      return false;
  }
}

