package features

import (
	"context"
	"fmt"
	"slices"
	"strings"
	"sync"

	"github.com/speakeasy-api/openapi-generation/v2/internal/executor"
	"github.com/speakeasy-api/openapi-generation/v2/internal/types"
	"github.com/speakeasy-api/openapi-generation/v2/pkg/logging"
	"go.uber.org/zap"
)

type FeatureExecutor struct {
	executor           *executor.Executor
	baseTemplateConfig map[string]any
	target             types.Target

	isFeatureSupportedCache             sync.Map
	isFeatureEnabledCache               sync.Map
	isFeatureIgnoredCache               sync.Map
	isUnionWrapperCache                 sync.Map
	getFeatureVersionCache              sync.Map
	isReadmeSectionImplementedCache     sync.Map
	isReadmeSectionIgnoredCache         sync.Map
	allSupportedFeaturesCache           sync.Map
	autoGeneratedHeaderCache            sync.Map
	staticallyUsedFeaturesCache         sync.Map
	isTestSkippedCache                  sync.Map
	collectGlobalsAndServersModelsCache sync.Map
}

func NewFeatureExecutor(executor *executor.Executor, baseTemplateConfig map[string]any, target types.Target) *FeatureExecutor {
	return &FeatureExecutor{
		executor:           executor,
		baseTemplateConfig: baseTemplateConfig,
		target:             target,
	}
}

func (f *FeatureExecutor) runFunctionWithCache(ctx context.Context, functionName string, cache *sync.Map, key string, defaultVal any, args ...any) any {
	val, ok := cache.Load(key)
	if ok {
		return val
	}

	val, err := f.executor.Run(functionName, args...)
	if err != nil {
		logging.From(ctx).Debug(fmt.Sprintf("unable to run function %s, defaulting to %v", functionName, defaultVal), zap.Error(err))
		val = defaultVal
	} else if val == nil {
		val = defaultVal
	}

	cache.Store(key, val)

	return val
}

func (f *FeatureExecutor) IsFeatureSupported(ctx context.Context, feature Feature) bool {
	return f.runFunctionWithCache(ctx, "isFeatureSupported", &f.isFeatureSupportedCache, feature.String(), false, feature.String()).(bool)
}

func (f *FeatureExecutor) IsFeatureEnabled(ctx context.Context, feature Feature) bool {
	return f.runFunctionWithCache(ctx, "isFeatureEnabled", &f.isFeatureEnabledCache, feature.String(), false, feature.String(), f.baseTemplateConfig).(bool)
}

func (f *FeatureExecutor) IsFeatureIgnored(ctx context.Context, feature Feature) bool {
	return f.runFunctionWithCache(ctx, "isFeatureIgnored", &f.isFeatureIgnoredCache, feature.String(), false, feature.String()).(bool)
}

func (f *FeatureExecutor) IsUnionWrapper(ctx context.Context) bool {
	return f.runFunctionWithCache(ctx, "isUnionWrapper", &f.isUnionWrapperCache, "isUnionWrapper", false).(bool)
}

func (f *FeatureExecutor) GetFeatureVersion(ctx context.Context, feature Feature) string {
	return f.runFunctionWithCache(ctx, "getFeatureVersion", &f.getFeatureVersionCache, feature.String(), "0.0.0", feature.String()).(string)
}

func (f *FeatureExecutor) IsReadmeSectionImplemented(ctx context.Context, readmeSectionID string) bool {
	return f.runFunctionWithCache(ctx, "isReadmeSectionImplemented", &f.isReadmeSectionImplementedCache, readmeSectionID, false, readmeSectionID).(bool)
}

func (f *FeatureExecutor) IsReadmeSectionIgnored(ctx context.Context, readmeSectionID string) bool {
	if slices.Contains([]string{"postman", "terraform"}, f.target.Template) {
		return true
	}

	return f.runFunctionWithCache(ctx, "isReadmeSectionIgnored", &f.isReadmeSectionIgnoredCache, readmeSectionID, false, readmeSectionID).(bool)
}

func (f *FeatureExecutor) GetAvailableFeatures(ctx context.Context) map[string]bool {
	val := f.runFunctionWithCache(ctx, "allSupportedFeatures", &f.allSupportedFeaturesCache, "allSupportedFeatures", []any{})

	availableFeatures := make(map[string]bool)

	for _, feature := range val.([]any) {
		availableFeatures[feature.(string)] = true
	}

	return availableFeatures
}

// generatedIDPlaceholder is used to cache the header template with a placeholder
// that gets replaced with the actual ID at runtime
const generatedIDPlaceholder = "00000000-0000-0000-0000-000000000000"

func (f *FeatureExecutor) GetAutoGeneratedHeader(ctx context.Context, generatedID string) string {
	// Call the template function with the placeholder ID for caching
	header := f.runFunctionWithCache(ctx, "getAutoGeneratedHeader", &f.autoGeneratedHeaderCache, "getAutoGeneratedHeader", "", generatedIDPlaceholder, f.baseTemplateConfig).(string)

	// If we have an actual ID and the header contains the placeholder, replace it
	if generatedID != "" && generatedID != generatedIDPlaceholder {
		header = strings.ReplaceAll(header, generatedIDPlaceholder, generatedID)
	} else if generatedID == "" {
		// If no ID provided, remove the placeholder line entirely
		// This handles cases where persistent edits is disabled
		header = removeGeneratedIDLine(header, generatedIDPlaceholder)
	}

	return header
}

// removeGeneratedIDLine removes the line containing the placeholder ID from the header
func removeGeneratedIDLine(header, placeholder string) string {
	lines := strings.Split(header, "\n")
	var result []string
	for _, line := range lines {
		if !strings.Contains(line, placeholder) {
			result = append(result, line)
		}
	}
	return strings.Join(result, "\n")
}

// Will return a list of features that are used by the template on all generations
func (f *FeatureExecutor) GetStaticallyUsedFeatures(ctx context.Context) []Feature {
	val := f.runFunctionWithCache(ctx, "getStaticallyUsedFeatures", &f.staticallyUsedFeaturesCache, "getStaticallyUsedFeatures", []any{})

	if val == nil {
		return nil
	}

	staticFeatures := []Feature{}

	for _, feature := range val.([]any) {
		staticFeatures = append(staticFeatures, FeatureFromString(feature.(string)))
	}

	return staticFeatures
}

func (f *FeatureExecutor) IsTestSkipped(ctx context.Context, test Test) bool {
	if slices.Contains([]string{"postman", "terraform"}, f.target.Template) {
		return true
	}

	return f.runFunctionWithCache(ctx, "isTestSkipped", &f.isTestSkippedCache, test.String(), false, test.String()).(bool)
}

func (f *FeatureExecutor) CollectGlobalsAndServersModels(ctx context.Context) bool {
	return f.runFunctionWithCache(ctx, "collectGlobalsAndServersModels", &f.collectGlobalsAndServersModelsCache, "collectGlobalsAndServersModels", false).(bool)
}
