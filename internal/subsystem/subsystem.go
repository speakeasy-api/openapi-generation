type Sanitizer interface {
	SanitizeFileName(name string) string
	GetEnumNames(t *ast.TypeDef) []string
}

type Features interface {
	Target() types.Target
	GetImplementedFeaturesList(ctx context.Context) []features.Feature
	IsFeatureSupported(ctx context.Context, feature features.Feature) bool
	IsFeatureEnabled(ctx context.Context, feature features.Feature) bool
	IsFeatureIgnored(ctx context.Context, feature features.Feature) bool
	IsUnionWrapper(ctx context.Context) bool
	GetFeatureVersion(ctx context.Context, feature features.Feature) string
	IsReadmeSectionImplemented(ctx context.Context, readmeSectionID string) bool
	IsReadmeSectionIgnored(ctx context.Context, readmeSectionID string) bool
	RecordFeatureUsage(ctx context.Context, feature features.Feature)
	RegisterReadmeSectionTemplated(readmeSectionID string, feature features.Feature)
	ReinstateFeatureUsage(ctx context.Context, featureUsage map[string]bool)
	GetFeatureUsage(ctx context.Context) map[string]bool
	GetUsedFeatures(ctx context.Context) map[string]string
	GetAvailableFeatures(ctx context.Context) map[string]bool
	IsFeatureUsed(feature features.Feature) bool
	GetAutoGeneratedHeader(ctx context.Context, generatedID string) string
	CollectGlobalsAndServersModels(ctx context.Context) bool
}

// Subsystem represents the subsystems of the generator that are normally used by multiple other packages in addition to the generator itself
// This container class was create to make it simpler to pass around and standardize access to avoid large param lists or options objects
type Subsystem struct {
	Config      *configuration.Config  // the parsed configuration (usually from gen.yaml)
	Features    Features               // system for managing feature enablement and recording of used features
	Extensions  *extensions.Extensions // system for parsing extensions and handling extension rewrites
	Register    *register.Register     // type system register
	Target      types.Target
	Cycles      *cycles.CycleDetector
	Sanitizer   Sanitizer
	FileTracker *filetracking.Tracker
	Patches     *patches.Subsystem // system for 3-way merge with persistent edits
}

func New(fileTracker *filetracking.Tracker) *Subsystem {
	return &Subsystem{
		Register:    register.New(),
		Cycles:      cycles.New(),
		FileTracker: fileTracker,
	}
}

type InitOptions struct {
	Target              types.Target
	Config              *configuration.Config
	BaseTemplateConfigs map[string]any
	OutDir              string
	GenLockId           string
	FS                  filesystem.FileSystem
	Git                 merge.Git
	LockFile            *config.LockFile
}

func (s *Subsystem) Init(ctx context.Context, opts InitOptions) error {
	if opts.FS == nil {
		return errors.New("cannot initialize file tracking without a file system")
	}

	fileTrackerOpts := filetracking.Options{
		OutDir:    opts.OutDir,
		GenLockId: opts.GenLockId,
		FS:        opts.FS,
		// When persistent edits is enabled, files are written atomically at the end
		// so we don't need the incremental crash-recovery lock file.
		SkipTempLockFile: opts.Config.Generation.PersistentEdits.IsEnabled(),
		// When persistent edits is explicitly disabled, nothing consumes
		// last_write_checksum; omitting it keeps gen.lock merge-conflict free.
		SkipChecksums: opts.Config.Generation.PersistentEdits.IsNever(),
	}
	if s.FileTracker == nil {
		s.FileTracker = filetracking.NewTracker(ctx, fileTrackerOpts)
	} else if s.FileTracker.Options != fileTrackerOpts {
		// We can't create a new instance because the in memory files would be lost
		return errors.New("file tracker options mismatch")
	}

	s.Target = opts.Target
	s.Extensions = extensions.New(opts.Target)

	var err error
	s.Features, err = features.New(opts.Target, opts.BaseTemplateConfigs)
	if err != nil {
		return err
	}

	s.Config = opts.Config

	s.Register.Config = s.Config

	// Initialize patches subsystem - always created, but Enabled controls behavior
	persistentEditsEnabled := s.Config.Generation.PersistentEdits.Enabled
	s.Patches = patches.NewSubsystem(
		opts.Config,
		opts.FS,
		opts.Git,
		opts.LockFile,
		s.FileTracker,
		opts.OutDir,
		persistentEditsEnabled,
	)

	return nil
}
