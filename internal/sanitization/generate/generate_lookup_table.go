package main

import (
	"fmt"
	"log"
	"os"
	"path/filepath"
	"strings"
	"unicode"

	"golang.org/x/text/runes"
	"golang.org/x/text/transform"
	"golang.org/x/text/unicode/norm"
)

func main() {
	var sb strings.Builder

	sb.WriteString(`// Code generated by internal/sanitization/generate_lookup_table.go DO NOT EDIT.
package sanitization

var normalizedDiatriticsLookup = map[rune]rune{
`)

	for codePoint := rune(0); codePoint <= 0x10FFFF; codePoint++ {
		in := string(codePoint)
		out := normalizeDiacritics(in)

		if out != in {
			o := []rune(out)
			if len(o) != 1 {
				continue
			}

			c := o[0]
			if (c < 'a' || c > 'z') && (c < 'A' || c > 'Z') {
				continue
			}

			fmt.Fprintf(&sb, `	'%c': '%c',`+"\n", codePoint, o[0])
		}
	}

	sb.WriteString(`}`)

	pwd, err := os.Getwd()
	if err != nil {
		log.Fatal(err)
	}

	err = os.WriteFile(filepath.Join(pwd, "lookup_table.go"), []byte(sb.String()), 0o644)
	if err != nil {
		log.Fatal(err)
	}
}

func normalizeDiacritics(in string) string {
	t := transform.Chain(norm.NFD, runes.Remove(runes.In(unicode.Mn)), norm.NFC)
	result, _, err := transform.String(t, in)
	if err != nil {
		return "_"
	}

	return result
}
