// CommonTestSetup encapsulates the common test setup components
type CommonTestSetup struct {
	DocInfo   *document.DocumentInfo
	Target    types.Target
	Config    *configuration.Config
	Subsystem *subsystem.Subsystem
	Namer     *namer.Namer
}

func DefaultFixes() *config.Fixes {
	return &config.Fixes{
		NameResolutionFeb2025:                true,
		NameResolutionDec2023:                false,
		RequestResponseComponentNamesFeb2024: false,
		NameOverrideFeb2026:                  true,
	}
}

func WithNameOverrideFeb2026(v bool) *config.Fixes {
	f := DefaultFixes()
	f.NameOverrideFeb2026 = v
	return f
}

// TestEnvironmentOptions provides configuration options for test environment setup
type TestEnvironmentOptions struct {
	// OpenAPI YAML content
	OpenAPIYAML string

	// Configuration fixes
	Fixes *config.Fixes

	// Feature configuration - can use either feature maps OR MockFeaturesConfig
	SupportedFeatures map[features.Feature]bool
	EnabledFeatures   map[features.Feature]bool
	MockFeatures      *MockFeaturesConfig

	Schemas *config.Schemas

	// Target language (defaults to "go")
	Target string

	// Whether to maintain OpenAPI field order (defaults to false)
	MaintainOpenAPIOrder *bool
}

// MockFeaturesConfig allows configuring the behavior of MockFeatures
type MockFeaturesConfig struct {
	Target                         types.Target
	SupportedFeatures              map[features.Feature]bool
	EnabledFeatures                map[features.Feature]bool
	IgnoredFeatures                map[features.Feature]bool
	FeatureVersions                map[features.Feature]string
	IsUnionWrapper                 bool
	ReadmeSectionImplemented       map[string]bool
	ReadmeSectionIgnored           map[string]bool
	AvailableFeatures              map[string]bool
	UsedFeatures                   map[features.Feature]bool
	AutoGeneratedHeader            string
	CollectGlobalsAndServersModels bool
}

// NewMockFeaturesConfig creates a default configuration for MockFeatures
func NewMockFeaturesConfig() *MockFeaturesConfig {
	return &MockFeaturesConfig{
		Target:                         types.Target{Target: "go"},
		SupportedFeatures:              make(map[features.Feature]bool),
		EnabledFeatures:                make(map[features.Feature]bool),
		IgnoredFeatures:                make(map[features.Feature]bool),
		FeatureVersions:                make(map[features.Feature]string),
		IsUnionWrapper:                 false,
		ReadmeSectionImplemented:       make(map[string]bool),
		ReadmeSectionIgnored:           make(map[string]bool),
		AvailableFeatures:              make(map[string]bool),
		UsedFeatures:                   make(map[features.Feature]bool),
		AutoGeneratedHeader:            "",
		CollectGlobalsAndServersModels: false,
	}
}

// WithSupportAllFeatures configures the mock to support all features by default
func (c *MockFeaturesConfig) WithSupportAllFeatures() *MockFeaturesConfig {
	// Set default behavior to support all features
	c.SupportedFeatures = nil // nil means support all
	// Ensure UsedFeatures is initialized
	if c.UsedFeatures == nil {
		c.UsedFeatures = make(map[features.Feature]bool)
	}
	return c
}

// WithTarget sets the target for the mock
func (c *MockFeaturesConfig) WithTarget(target types.Target) *MockFeaturesConfig {
	c.Target = target
	return c
}

// SetupTestEnvironment creates a complete test environment with the given configuration
func SetupTestEnvironment(opts TestEnvironmentOptions) (*CommonTestSetup, error) {
	ctx := context.Background()
	doc, _, err := openapi.Unmarshal(ctx, bytes.NewReader([]byte(opts.OpenAPIYAML)))
	if err != nil {
		return nil, err
	}

	// Create docInfo early so we can use it for populating the registry
	docInfo := &document.DocumentInfo{
		Doc:        doc,
		Schema:     []byte(opts.OpenAPIYAML),
		SchemaPath: "test.yaml",
		IsRemote:   false,
	}

	// Reset and populate the global nested reference registry from the document.
	// This must be done before any schema processing to ensure document order
	// is respected for the SharedNestedComponentsJan2026 feature flag.
	internalOpenAPI.ResetGlobalNestedRefRegistry()
	internalOpenAPI.PopulateFromDocument(ctx, docInfo)

	// Set up default fixes if not provided
	fixes := opts.Fixes
	if fixes == nil {
		fixes = DefaultFixes()
	}

	// Set up schemas
	schemas := opts.Schemas
	if schemas == nil {
		schemas = &config.Schemas{
			AllOfMergeStrategy: config.AllOfMergeStrategyShallowMerge,
		}
	}

	// Set up target
	targetLang := opts.Target
	if targetLang == "" {
		targetLang = "go"
	}

	maintainOrder := false
	if opts.MaintainOpenAPIOrder != nil {
		maintainOrder = *opts.MaintainOpenAPIOrder
	}

	baseConfig := &config.Configuration{
		Generation: config.Generation{
			MaintainOpenAPIOrder: maintainOrder,
			Fixes:                fixes,
			Schemas:              *schemas,
		},
		Languages: map[string]config.LanguageConfig{
			targetLang: {
				Cfg: map[string]any{
					"imports": configuration.ImportConfig{
						Option: configuration.ImportOptionOpenAPI,
					},
					"inputModelSuffix":  "Input",
					"outputModelSuffix": "Output",
					"enumFormat":        "enum",
				},
			},
		},
	}

	cfg := configuration.New(baseConfig, targetLang)

	// Create target
	target := types.Target{Target: targetLang}

	// Create extensions handler
	exts := extensions.New(target)

	// Create register
	reg := register.New()
	reg.Config = cfg

	// Set up features
	var featuresInstance *MockFeatures

	switch {
	case opts.MockFeatures != nil:
		// Use provided MockFeaturesConfig
		featuresInstance = NewMockFeatures(opts.MockFeatures)
	case opts.SupportedFeatures != nil || opts.EnabledFeatures != nil:
		// Convert feature maps to MockFeaturesConfig
		config := NewMockFeaturesConfig()
		config.SupportedFeatures = opts.SupportedFeatures
		config.EnabledFeatures = opts.EnabledFeatures
		featuresInstance = NewMockFeatures(config)
	default:
		// Use default (support all features, but with security-compatible defaults)
		config := NewMockFeaturesConfig().WithSupportAllFeatures()
		// Set security-compatible defaults to match security test expectations
		config.EnabledFeatures[features.FeatureEnvVarSecurityUsage] = false
		featuresInstance = NewMockFeatures(config)
	}

	// Create subsystem
	mockSubsystem := &subsystem.Subsystem{
		Extensions: exts,
		Features:   featuresInstance,
		Register:   reg,
		Config:     cfg,
		Target:     target,
	}

	// Create namer
	namerInstance := namer.New(mockSubsystem)

	return &CommonTestSetup{
		DocInfo:   docInfo,
		Target:    target,
		Config:    cfg,
		Subsystem: mockSubsystem,
		Namer:     namerInstance,
	}, nil
}

// MockFeatures is a configurable mock implementation of the subsystem.Features interface
type MockFeatures struct {
	config *MockFeaturesConfig
}

// NewMockFeatures creates a new MockFeatures with the given configuration
func NewMockFeatures(config *MockFeaturesConfig) *MockFeatures {
	if config == nil {
		config = NewMockFeaturesConfig().WithSupportAllFeatures()
	}
	return &MockFeatures{config: config}
}

func (m *MockFeatures) Target() types.Target {
	return m.config.Target
}

func (m *MockFeatures) GetImplementedFeaturesList(ctx context.Context) []features.Feature {
	var implemented []features.Feature
	for feature, supported := range m.config.SupportedFeatures {
		if supported {
			implemented = append(implemented, feature)
		}
	}
	return implemented
}

func (m *MockFeatures) IsFeatureSupported(ctx context.Context, feature features.Feature) bool {
	if m.config.SupportedFeatures == nil {
		// nil means support all features
		return true
	}
	return m.config.SupportedFeatures[feature]
}

func (m *MockFeatures) IsFeatureEnabled(ctx context.Context, feature features.Feature) bool {
	if enabled, exists := m.config.EnabledFeatures[feature]; exists {
		return enabled
	}
	// If feature is not supported, it should not be enabled
	if m.config.SupportedFeatures != nil {
		if supported, exists := m.config.SupportedFeatures[feature]; exists && !supported {
			return false
		}
	}
	// Default to enabled if not specified and supported
	return true
}

func (m *MockFeatures) IsFeatureIgnored(ctx context.Context, feature features.Feature) bool {
	return m.config.IgnoredFeatures[feature]
}

func (m *MockFeatures) IsUnionWrapper(ctx context.Context) bool {
	return m.config.IsUnionWrapper
}

func (m *MockFeatures) GetFeatureVersion(ctx context.Context, feature features.Feature) string {
	if version, exists := m.config.FeatureVersions[feature]; exists {
		return version
	}
	return "1.0.0" // Default version
}

func (m *MockFeatures) IsReadmeSectionImplemented(ctx context.Context, readmeSectionID string) bool {
	if implemented, exists := m.config.ReadmeSectionImplemented[readmeSectionID]; exists {
		return implemented
	}
	return true // Default to implemented
}

func (m *MockFeatures) IsReadmeSectionIgnored(ctx context.Context, readmeSectionID string) bool {
	return m.config.ReadmeSectionIgnored[readmeSectionID]
}

func (m *MockFeatures) RecordFeatureUsage(ctx context.Context, feature features.Feature) {
	// Ensure UsedFeatures is initialized
	if m.config.UsedFeatures == nil {
		m.config.UsedFeatures = make(map[features.Feature]bool)
	}
	// Record the feature as used
	m.config.UsedFeatures[feature] = true
}

func (m *MockFeatures) RegisterReadmeSectionTemplated(readmeSectionID string, feature features.Feature) {
	// No-op for testing
}

func (m *MockFeatures) ReinstateFeatureUsage(ctx context.Context, featureUsage map[string]bool) {
	// No-op for testing
}

func (m *MockFeatures) GetFeatureUsage(ctx context.Context) map[string]bool {
	usage := make(map[string]bool)
	for feature, used := range m.config.UsedFeatures {
		if used {
			usage[feature.String()] = true
		}
	}
	return usage
}

func (m *MockFeatures) GetUsedFeatures(ctx context.Context) map[string]string {
	used := make(map[string]string)
	for feature, isUsed := range m.config.UsedFeatures {
		if isUsed {
			used[feature.String()] = m.GetFeatureVersion(ctx, feature)
		}
	}
	return used
}

func (m *MockFeatures) GetAvailableFeatures(ctx context.Context) map[string]bool {
	return m.config.AvailableFeatures
}

func (m *MockFeatures) IsFeatureUsed(feature features.Feature) bool {
	return m.config.UsedFeatures[feature]
}

func (m *MockFeatures) GetAutoGeneratedHeader(ctx context.Context, generatedID string) string {
	return m.config.AutoGeneratedHeader
}

func (m *MockFeatures) CollectGlobalsAndServersModels(ctx context.Context) bool {
	return m.config.CollectGlobalsAndServersModels
}

// Helper functions for creating OpenAPI documents (from schemas tests)

// CreateOpenAPIDoc creates a full OpenAPI document with the given schemas YAML
func CreateOpenAPIDoc(schemasYAML string) string {
	return `openapi: 3.0.0
info:
  title: Test API
  version: 1.0.0
paths: {}
components:
  schemas:
` + IndentYAML(schemasYAML, "    ")
}

// IndentYAML indents YAML content with the given indent string
func IndentYAML(yaml string, indent string) string {
	lines := strings.Split(yaml, "\n")
	for i, line := range lines {
		if line != "" {
			lines[i] = indent + line
		}
	}
	return strings.Join(lines, "\n")
}
