package consts

import (
	"testing"

	"github.com/speakeasy-api/openapi-generation/v2/pkg/generate/snapshots/snaptest"
)

func TestSnapTsConstRespectRequiredMinimal(t *testing.T) {
	t.Parallel()
	spec := `openapi: 3.1.0
info:
  title: Const Values API
  version: 1.0.0
paths:
  /test:
    post:
      operationId: testConst
      requestBody:
        required: true
        content:
          application/json:
            schema:
              $ref: '#/components/schemas/ConstModel'
      responses:
        '200':
          description: OK
components:
  schemas:
    ConstModel:
      type: object
      required:
        - requiredConst
        - requiredConstDefault
        - requiredString
        - requiredStringDefault
      properties:
        requiredConst:
          type: string
          const: "required-const-value"
        requiredConstDefault:
          type: string
          const: "required-const-default-value"
          default: "required-const-default-value"
        optionalConst:
          type: string
          const: "optional-const-value"
        optionalConstDefault:
          type: string
          const: "optional-const-default-value"
          default: "optional-const-default-value"
        optionalString:
          type: string
        optionalDefaultString:
          type: string
          default: "optional-default-string-default-value"
        requiredString:
          type: string
        requiredStringDefault:
          type: string
          default: "required-string-default-value"
        `

	genYaml := `typescript:
  packageName: consttest
  constFieldsAlwaysOptional: false
`

	// expectedSnapshotFiles defines which generated files to include in the snapshot
	expectedSnapshotFiles := []string{
		"src/models/const-model.ts",
	}

	expectedSnapshot := `--- src/models/const-model.ts ---
/*
 * Code generated by Speakeasy (https://speakeasy.com). DO NOT EDIT.
 * Generated under the AGPL-3.0-only license.
 * SPDX-License-Identifier: AGPL-3.0-only
 */

import * as z from "zod/v4-mini";

export type ConstModel = {
  requiredConst: "required-const-value";
  requiredConstDefault?: "required-const-default-value" | undefined;
  optionalConst?: "optional-const-value" | undefined;
  optionalConstDefault?: "optional-const-default-value" | undefined;
  optionalString?: string | undefined;
  optionalDefaultString?: string | undefined;
  requiredString: string;
  requiredStringDefault?: string | undefined;
};

/** @internal */
export type ConstModel$Outbound = {
  requiredConst: "required-const-value";
  requiredConstDefault: "required-const-default-value";
  optionalConst?: "optional-const-value" | undefined;
  optionalConstDefault: "optional-const-default-value";
  optionalString?: string | undefined;
  optionalDefaultString: string;
  requiredString: string;
  requiredStringDefault: string;
};

/** @internal */
export const ConstModel$outboundSchema: z.ZodMiniType<
  ConstModel$Outbound,
  ConstModel
> = z.object({
  requiredConst: z.literal("required-const-value"),
  requiredConstDefault: z._default(
    z.literal("required-const-default-value"),
    "required-const-default-value" as const,
  ),
  optionalConst: z.optional(z.literal("optional-const-value")),
  optionalConstDefault: z._default(
    z.literal("optional-const-default-value"),
    "optional-const-default-value" as const,
  ),
  optionalString: z.optional(z.string()),
  optionalDefaultString: z._default(
    z.string(),
    "optional-default-string-default-value",
  ),
  requiredString: z.string(),
  requiredStringDefault: z._default(
    z.string(),
    "required-string-default-value",
  ),
});

export function constModelToJSON(constModel: ConstModel): string {
  return JSON.stringify(ConstModel$outboundSchema.parse(constModel));
}


` // end of snapshot

	snaptest.DoTestSnapshot(t, snaptest.Options{
		Spec:         spec,
		GenYaml:      genYaml,
		IncludeGlobs: expectedSnapshotFiles,
		Expected:     expectedSnapshot,
	})
}
