package snapshots

import (
	"testing"

	"github.com/speakeasy-api/openapi-generation/v2/pkg/generate/snapshots/snaptest"
)

func TestSnapTsBase(t *testing.T) {
	t.Parallel()
	spec := `openapi: 3.1.0
info:
  title: Pet API
  version: 1.0.0
paths:
  /pets:
    get:
      operationId: listPets
      responses:
        '200':
          description: OK
          content:
            application/json:
              schema:
                type: array
                items:
                  $ref: '#/components/schemas/Pet'
components:
  schemas:
    Pet:
      type: object
      required: [id, name]
      properties:
        id:
          type: integer
          format: int64
        name:
          type: string`

	// genYaml is partial and will be merged with target defaults
	genYaml := `typescript:
  packageName: petstore
`

	// expectedSnapshotFiles defines which generated files to include in the snapshot
	expectedSnapshotFiles := []string{
		"src/models/pet.ts",
	}

	expectedSnapshot := `--- src/models/pet.ts ---
/*
 * Code generated by Speakeasy (https://speakeasy.com). DO NOT EDIT.
 * Generated under the AGPL-3.0-only license.
 * SPDX-License-Identifier: AGPL-3.0-only
 */

import * as z from "zod/v4-mini";
import { safeParse } from "../lib/schemas.js";
import { Result as SafeParseResult } from "../types/fp.js";
import * as types from "../types/primitives.js";
import { SDKValidationError } from "./errors/sdk-validation-error.js";

export type Pet = {
  id: number;
  name: string;
};

/** @internal */
export const Pet$inboundSchema: z.ZodMiniType<Pet, unknown> = z.object({
  id: types.number(),
  name: types.string(),
});

export function petFromJSON(
  jsonString: string,
): SafeParseResult<Pet, SDKValidationError> {
  return safeParse(
    jsonString,
    (x) => Pet$inboundSchema.parse(JSON.parse(x)),
    ` + "`" + `Failed to parse 'Pet' from JSON` + "`" + `,
  );
}


` // end of snapshot

	snaptest.DoTestSnapshot(t, snaptest.Options{
		Spec:         spec,
		GenYaml:      genYaml,
		IncludeGlobs: expectedSnapshotFiles,
		Expected:     expectedSnapshot,
	})
}
