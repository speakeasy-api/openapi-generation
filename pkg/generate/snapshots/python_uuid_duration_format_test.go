package snapshots

import (
	"testing"

	"github.com/speakeasy-api/openapi-generation/v2/pkg/generate/snapshots/snaptest"
)

// TestSnapPyUUIDDurationFormat verifies the opt-in uuidFormat/durationFormat
// config flags map `format: uuid` to uuid.UUID and `format: duration` to
// datetime.timedelta instead of the default str.
func TestSnapPyUUIDDurationFormat(t *testing.T) {
	t.Parallel()
	spec := `openapi: 3.1.0
info:
  title: Worker API
  version: 1.0.0
paths:
  /worker:
    get:
      operationId: getWorkerInfo
      responses:
        '200':
          description: OK
          content:
            application/json:
              schema:
                $ref: '#/components/schemas/WorkerInfo'
components:
  schemas:
    WorkerInfo:
      type: object
      required: [id, timeout, created_at]
      properties:
        id:
          type: string
          format: uuid
        timeout:
          type: string
          format: duration
        created_at:
          type: string
          format: date-time`

	// genYaml is partial and will be merged with target defaults.
	// uuidFormat and durationFormat are opt-in and default to false.
	genYaml := `python:
  packageName: worker
  uuidFormat: true
  durationFormat: true
`

	expectedSnapshotFiles := []string{
		"src/worker/models/workerinfo.py",
	}

	expectedSnapshot := `--- src/worker/models/workerinfo.py ---
"""Code generated by Speakeasy (https://speakeasy.com). DO NOT EDIT."""
# Generated under the AGPL-3.0-only license.
# SPDX-License-Identifier: AGPL-3.0-only

from __future__ import annotations
from datetime import datetime, timedelta
from typing_extensions import TypedDict
from uuid import UUID
from worker.types import BaseModel


class WorkerInfoTypedDict(TypedDict):
    id: UUID
    timeout: timedelta
    created_at: datetime


class WorkerInfo(BaseModel):
    id: UUID

    timeout: timedelta

    created_at: datetime


` // end of snapshot

	snaptest.DoTestSnapshot(t, snaptest.Options{
		Spec:         spec,
		GenYaml:      genYaml,
		IncludeGlobs: expectedSnapshotFiles,
		Expected:     expectedSnapshot,
	})
}

