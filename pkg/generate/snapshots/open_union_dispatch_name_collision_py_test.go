package snapshots

import (
	"testing"

	"github.com/speakeasy-api/openapi-generation/v2/pkg/generate/snapshots/snaptest"
)

// TestSnapPyOpenUnionDispatchNameCollision covers a union of open
// discriminated unions whose other member is a schema named WrapValidator.
// Without conflict-resistant model imports, the model is imported by its bare
// name into the module that declares the dispatching union, so the Pydantic
// validator must be referenced through the pydantic module.
func TestSnapPyOpenUnionDispatchNameCollision(t *testing.T) {
	t.Parallel()

	spec := `openapi: 3.1.0
info:
  title: Open Union Dispatch Name Collision
  version: 1.0.0
paths:
  /envelope:
    post:
      operationId: postEnvelope
      requestBody:
        required: true
        content:
          application/json:
            schema:
              $ref: '#/components/schemas/Envelope'
      responses:
        '200':
          description: OK
          content:
            application/json:
              schema:
                $ref: '#/components/schemas/Envelope'
components:
  schemas:
    Envelope:
      type: object
      properties:
        item:
          anyOf:
            - $ref: '#/components/schemas/WrapValidator'
            - $ref: '#/components/schemas/Label'
            - $ref: '#/components/schemas/Shape'
    WrapValidator:
      type: object
      required: [note]
      properties:
        note:
          type: string
    Label:
      oneOf:
        - $ref: '#/components/schemas/TextLabel'
        - $ref: '#/components/schemas/NumberLabel'
      discriminator:
        propertyName: kind
        mapping:
          text: '#/components/schemas/TextLabel'
          number: '#/components/schemas/NumberLabel'
    TextLabel:
      type: object
      required: [kind, text]
      properties:
        kind:
          type: string
          enum: [text]
        text:
          type: string
    NumberLabel:
      type: object
      required: [kind, number]
      properties:
        kind:
          type: string
          enum: [number]
        number:
          type: integer
    Shape:
      oneOf:
        - $ref: '#/components/schemas/Circle'
        - $ref: '#/components/schemas/Square'
      discriminator:
        propertyName: kind
        mapping:
          circle: '#/components/schemas/Circle'
          square: '#/components/schemas/Square'
    Circle:
      type: object
      required: [kind, radius]
      properties:
        kind:
          type: string
          enum: [circle]
        radius:
          type: integer
    Square:
      type: object
      required: [kind, side]
      properties:
        kind:
          type: string
          enum: [square]
        side:
          type: integer
`

	genYaml := `python:
  packageName: sdk
  fixFlags:
    conflictResistantModelImportsFeb2026: false
  forwardCompatibleUnionsByDefault: tagged-only
`

	expectedSnapshotFiles := []string{
		"src/sdk/models/envelope.py",
	}

	expectedSnapshot := `--- src/sdk/models/envelope.py ---
"""Code generated by Speakeasy (https://speakeasy.com). DO NOT EDIT."""
# Generated under the AGPL-3.0-only license.
# SPDX-License-Identifier: AGPL-3.0-only

from __future__ import annotations
from .label import Label, LabelTypedDict
from .shape import Shape, ShapeTypedDict
from .wrapvalidator import WrapValidator, WrapValidatorTypedDict
from functools import partial
import pydantic
from pydantic import model_serializer
from sdk.types import (
    BaseModel,
    UNSET_SENTINEL,
    current_exclude_none,
    serialize_with_info,
)
from sdk.types.basemodel import current_filtered_dump
from sdk.utils.unions import dispatch_open_union_members
from typing import Optional, Union
from typing_extensions import Annotated, NotRequired, TypeAliasType, TypedDict


ItemTypedDict = TypeAliasType(
    "ItemTypedDict", Union[WrapValidatorTypedDict, LabelTypedDict, ShapeTypedDict]
)


Item = TypeAliasType(
    "Item",
    Annotated[
        Union[WrapValidator, Label, Shape],
        pydantic.WrapValidator(
            partial(dispatch_open_union_members, members=(Label, Shape))
        ),
    ],
)


class EnvelopeTypedDict(TypedDict):
    item: NotRequired[ItemTypedDict]


class Envelope(BaseModel):
    item: Optional[Item] = None

    @model_serializer(mode="wrap")
    def _serialize_model_with_info(self, handler, info):
        return serialize_with_info(self.serialize_model, handler, info)

    def serialize_model(self, handler):
        optional_fields = set(["item"])
        exclude_none = current_exclude_none()
        skip_filtered = exclude_none is False or current_filtered_dump()
        serialized = handler(self)
        m = {}

        for n, f in type(self).model_fields.items():
            k = f.alias if f.alias is not None else n
            if k not in serialized and n not in serialized and skip_filtered:
                continue
            val = serialized.get(k, serialized.get(n))

            if val != UNSET_SENTINEL:
                if val is not None or k not in optional_fields:
                    m[k] = val

        return m


` // end of snapshot

	snaptest.DoTestSnapshot(t, snaptest.Options{
		Spec:         spec,
		GenYaml:      genYaml,
		IncludeGlobs: expectedSnapshotFiles,
		Expected:     expectedSnapshot,
	})
}
