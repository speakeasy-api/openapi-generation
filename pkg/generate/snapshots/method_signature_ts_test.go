package snapshots

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/speakeasy-api/openapi-generation/v2/pkg/generate/snapshots/snaptest"
	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func TestSnapTsParamsObjectMethodSignature(t *testing.T) {
	t.Parallel()

	spec := `openapi: 3.1.0
info:
  title: Params Object API
  version: 1.0.0
servers:
  - url: https://api.example.com
paths:
  /agents:
    post:
      operationId: createAgent
      x-speakeasy-group: agents
      requestBody:
        required: true
        content:
          application/json:
            schema:
              $ref: "#/components/schemas/Agent"
      responses:
        "200":
          description: OK
          content:
            application/json:
              schema:
                $ref: "#/components/schemas/Agent"
    get:
      operationId: listAgents
      x-speakeasy-group: agents
      parameters:
        - name: page_size
          in: query
          schema:
            type: integer
        - name: page_token
          in: query
          schema:
            type: string
      responses:
        "200":
          description: OK
          content:
            application/json:
              schema:
                $ref: "#/components/schemas/Agent"
  /agents/{id}:
    get:
      operationId: getAgent
      x-speakeasy-group: agents
      parameters:
        - name: id
          in: path
          required: true
          schema:
            type: string
        - name: include_deleted
          in: query
          schema:
            type: boolean
      responses:
        "200":
          description: OK
          content:
            application/json:
              schema:
                $ref: "#/components/schemas/Agent"
components:
  schemas:
    Agent:
      type: object
      required: [name]
      properties:
        name:
          type: string
        description:
          type: string`

	genYaml := `typescript:
  packageName: params-object
  methodSignature: params-object
  flattenRequests: true
  maxMethodParams: 999
`

	expectedSnapshot := `--- src/models/operations/method-params.ts ---
/*
 * Code generated by Speakeasy (https://speakeasy.com). DO NOT EDIT.
 * Generated under the AGPL-3.0-only license.
 * SPDX-License-Identifier: AGPL-3.0-only
 */

import type { Agent } from "../agent.js";
import type { GetAgentRequest } from "./get-agent.js";
import type { ListAgentsRequest } from "./list-agents.js";

export type AgentParams = Agent;

export type GetAgentParams = Omit<
  GetAgentRequest,
  "id"
>;

export type ListAgentsParams = ListAgentsRequest;


` // end of snapshot

	snaptest.DoTestSnapshot(t, snaptest.Options{
		Spec:         spec,
		GenYaml:      genYaml,
		IncludeGlobs: []string{"src/models/operations/method-params.ts"},
		Expected:     expectedSnapshot,
		AfterGenerate: func(t *testing.T, tempDir string) {
			t.Helper()

			sdk, err := os.ReadFile(filepath.Join(tempDir, "src/sdk/agents.ts"))
			require.NoError(t, err)
			source := string(sdk)
			assert.Contains(t, source, "params?: ListAgentsParams,")
			assert.Contains(t, source, "id: string,\n    params?: GetAgentParams,")
			assert.Contains(t, source, "params?.pageSize")
			assert.Contains(t, source, "params?.includeDeleted")
		},
	})
}
