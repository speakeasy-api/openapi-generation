// Regression guard for the java8 arm of pagination stream-unwrapping with
// getterStyle=raw. Stream.ofNullable is a Java 9+ API; on the java8 arm the
// generated callAsStreamUnwrapped must route through
// Java8Compat.streamOfNullable instead. No CI variant crosses
// languageVersion=8 with getterStyle=raw (tertiary, the only java8 variant,
// uses always-optional), so this snapshot pins that combination and relies on
// the snapshot compile step to catch regressions.
