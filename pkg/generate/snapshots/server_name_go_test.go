package snapshots

import (
	"testing"

	"github.com/speakeasy-api/openapi-generation/v2/pkg/generate/snapshots/snaptest"
)

func TestSnapGoServerName(t *testing.T) {
	t.Parallel()
	spec := `openapi: 3.1.0
info:
  title: Server Name API
  version: 1.0.0
servers:
  - url: https://api.example.com
    description: The production server.
    name: production
  - url: https://sandbox.example.com
    description: The sandbox server.
    name: sandbox
paths:
  /items:
    get:
      operationId: listItems
      responses:
        '200':
          description: OK`

	genYaml := `go:
  packageName: github.com/example/server-name
`

	expectedSnapshotFiles := []string{
		"internal/config/sdkconfiguration.go",
	}

	expectedSnapshot := `--- internal/config/sdkconfiguration.go ---
// Code generated by Speakeasy (https://speakeasy.com). DO NOT EDIT.
// Generated under the AGPL-3.0-only license.
// SPDX-License-Identifier: AGPL-3.0-only

package config

import (
	"github.com/example/server-name/retry"
	"net/http"
	"time"
)

type HTTPClient interface {
	Do(req *http.Request) (*http.Response, error)
}

type SDKConfiguration struct {
	Client HTTPClient

	ServerURL         string
	Server            string
	ServerList        map[string]string
	UserAgent         string
	SDKVersion        string
	GenVersion        string
	OpenAPIDocVersion string
	RetryConfig       *retry.Config
	Timeout           *time.Duration
}

func (c *SDKConfiguration) GetServerDetails() (string, map[string]string) {
	if c.ServerURL != "" {
		return c.ServerURL, nil
	}

	if c.Server == "" {
		c.Server = "production"
	}

	return c.ServerList[c.Server], nil
}


` // end of snapshot

	snaptest.DoTestSnapshot(t, snaptest.Options{
		Spec:         spec,
		GenYaml:      genYaml,
		IncludeGlobs: expectedSnapshotFiles,
		Expected:     expectedSnapshot,
	})
}
