package snapshots

import (
	"testing"

	"github.com/speakeasy-api/openapi-generation/v2/pkg/generate/snapshots/snaptest"
)

// TestSnapPyFieldAliasModelRebuild ensures that Python models with camelCase field aliases
// (generated from camelCase OpenAPI properties) include model_rebuild() calls.
//
// Background: When a Python model uses `from __future__ import annotations` (which enables
// lazy annotation evaluation), pydantic's Field(alias=...) metadata is not resolved until
// model_rebuild() is called. Without model_rebuild(), the aliases are silently lost and
// fields serialize with snake_case names instead of the correct camelCase names.
//
// This is a regression test for the bug where models NOT involved in circular references
// were missing model_rebuild() calls. The fix ensures model_rebuild() is called for ALL
// model types, not just those in circular reference chains.
func TestSnapPyFieldAliasModelRebuild(t *testing.T) {
	t.Parallel()

	// Spec with camelCase properties that will generate snake_case Python fields
	// with Field(alias="camelCase") annotations. Crucially, UserProfile has NO
	// circular references - it's a standalone model.
	spec := `openapi: 3.1.0
info:
  title: User API
  version: 1.0.0
paths:
  /users:
    get:
      operationId: listUsers
      responses:
        '200':
          description: OK
          content:
            application/json:
              schema:
                type: array
                items:
                  $ref: '#/components/schemas/UserProfile'
components:
  schemas:
    UserProfile:
      type: object
      required:
        - firstName
        - lastName
        - emailAddress
      properties:
        firstName:
          type: string
        lastName:
          type: string
        emailAddress:
          type: string
        phoneNumber:
          type: string`

	genYaml := `python:
  packageName: userapi
`

	expectedSnapshotFiles := []string{
		"src/userapi/models/userprofile.py",
	}

	expectedSnapshot := `--- src/userapi/models/userprofile.py ---
"""Code generated by Speakeasy (https://speakeasy.com). DO NOT EDIT."""
# Generated under the AGPL-3.0-only license.
# SPDX-License-Identifier: AGPL-3.0-only

from __future__ import annotations
import pydantic
from pydantic import model_serializer
from typing import Optional
from typing_extensions import Annotated, NotRequired, TypedDict
from userapi.types import BaseModel, UNSET_SENTINEL


class UserProfileTypedDict(TypedDict):
    first_name: str
    last_name: str
    email_address: str
    phone_number: NotRequired[str]


class UserProfile(BaseModel):
    first_name: Annotated[str, pydantic.Field(alias="firstName")]

    last_name: Annotated[str, pydantic.Field(alias="lastName")]

    email_address: Annotated[str, pydantic.Field(alias="emailAddress")]

    phone_number: Annotated[Optional[str], pydantic.Field(alias="phoneNumber")] = None

    @model_serializer(mode="wrap")
    def serialize_model(self, handler):
        optional_fields = set(["phoneNumber"])
        serialized = handler(self)
        m = {}

        for n, f in type(self).model_fields.items():
            k = f.alias or n
            val = serialized.get(k, serialized.get(n))

            if val != UNSET_SENTINEL:
                if val is not None or k not in optional_fields:
                    m[k] = val

        return m


try:
    UserProfile.model_rebuild()
except NameError:
    pass


` // end of snapshot

	snaptest.DoTestSnapshot(t, snaptest.Options{
		Spec:         spec,
		GenYaml:      genYaml,
		IncludeGlobs: expectedSnapshotFiles,
		Expected:     expectedSnapshot,
	})
}
