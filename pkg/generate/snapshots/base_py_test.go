package snapshots

import (
	"testing"

	"github.com/speakeasy-api/openapi-generation/v2/pkg/generate/snapshots/snaptest"
)

func TestSnapPyBase(t *testing.T) {
	t.Parallel()
	spec := `openapi: 3.1.0
info:
  title: Pet API
  version: 1.0.0
paths:
  /pets:
    get:
      operationId: listPets
      responses:
        '200':
          description: OK
          content:
            application/json:
              schema:
                type: array
                items:
                  $ref: '#/components/schemas/Pet'
components:
  schemas:
    Pet:
      type: object
      required: [id, name]
      properties:
        id:
          type: integer
          format: int64
        name:
          type: string`

	// genYaml is partial and will be merged with target defaults
	genYaml := `python:
  packageName: petstore
`

	// expectedSnapshotFiles defines which generated files to include in the snapshot
	expectedSnapshotFiles := []string{
		"src/petstore/models/pet.py",
	}

	expectedSnapshot := `--- src/petstore/models/pet.py ---
"""Code generated by Speakeasy (https://speakeasy.com). DO NOT EDIT."""
# Generated under the AGPL-3.0-only license.
# SPDX-License-Identifier: AGPL-3.0-only

from __future__ import annotations
from petstore.types import BaseModel
from typing_extensions import TypedDict


class PetTypedDict(TypedDict):
    id: int
    name: str


class Pet(BaseModel):
    id: int

    name: str


` // end of snapshot

	snaptest.DoTestSnapshot(t, snaptest.Options{
		Spec:         spec,
		GenYaml:      genYaml,
		IncludeGlobs: expectedSnapshotFiles,
		Expected:     expectedSnapshot,
	})
}
