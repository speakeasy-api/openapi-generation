package snapshots

import (
	"testing"

	"github.com/speakeasy-api/openapi-generation/v2/pkg/generate/snapshots/snaptest"
)

// TestSnapPySerializeAsAnyOptionalNullableDiscriminatedUnion covers the
// SerializeAsAny wrap applied to optional-and-nullable discriminated-union
// request fields.
//
// A field typed OptionalNullable[<closed discriminated union>] expands to
// Union[union, None, Unset]. Under Pydantic 2.13 the present union value is
// matched against the Unset arm during serialization, which emits the UNSET
// sentinel and the enclosing model_serializer then drops the field. Wrapping
// the field in SerializeAsAny forces runtime-type serialization, preserving it
// on both 2.12.x and 2.13.x.
//
// The wrap only targets closed discriminated unions (Field(discriminator=...));
// open (forward-compatible) unions serialize as a plain Union and are not
// affected, so forwardCompatibleUnionsByDefault is disabled here to force the
// closed form.
func TestSnapPySerializeAsAnyOptionalNullableDiscriminatedUnion(t *testing.T) {
	t.Parallel()

	spec := `openapi: 3.1.0
info:
  title: SerializeAsAny Discriminated Union
  version: 1.0.0
paths:
  /run:
    post:
      operationId: createRun
      requestBody:
        required: true
        content:
          application/json:
            schema:
              $ref: '#/components/schemas/Body'
      responses:
        '200':
          description: OK
components:
  schemas:
    Body:
      type: object
      required:
        - name
      properties:
        name:
          type: string
        executionConfig:
          anyOf:
            - oneOf:
                - $ref: '#/components/schemas/AlphaConfig'
                - $ref: '#/components/schemas/BetaConfig'
              discriminator:
                propertyName: type
                mapping:
                  alpha: '#/components/schemas/AlphaConfig'
                  beta: '#/components/schemas/BetaConfig'
            - type: "null"
    AlphaConfig:
      type: object
      required:
        - type
        - path
      properties:
        type:
          type: string
          const: alpha
        path:
          type: string
    BetaConfig:
      type: object
      required:
        - type
        - path
      properties:
        type:
          type: string
          const: beta
        path:
          type: string
`

	genYaml := `python:
  packageName: sdk
  forwardCompatibleUnionsByDefault: false
  preApplyUnionDiscriminators: true
`

	expectedSnapshotFiles := []string{
		"src/sdk/models/body.py",
	}

	expectedSnapshot := `--- src/sdk/models/body.py ---
"""Code generated by Speakeasy (https://speakeasy.com). DO NOT EDIT."""
# Generated under the AGPL-3.0-only license.
# SPDX-License-Identifier: AGPL-3.0-only

from __future__ import annotations
from .alphaconfig import AlphaConfig, AlphaConfigTypedDict
from .betaconfig import BetaConfig, BetaConfigTypedDict
import pydantic
from pydantic import Field, SerializeAsAny, model_serializer
from sdk.types import BaseModel, Nullable, OptionalNullable, UNSET, UNSET_SENTINEL
from typing import Union
from typing_extensions import Annotated, NotRequired, TypeAliasType, TypedDict


ExecutionConfigTypedDict = TypeAliasType(
    "ExecutionConfigTypedDict", Union[AlphaConfigTypedDict, BetaConfigTypedDict]
)


ExecutionConfig = Annotated[Union[AlphaConfig, BetaConfig], Field(discriminator="type")]


class BodyTypedDict(TypedDict):
    name: str
    execution_config: NotRequired[Nullable[ExecutionConfigTypedDict]]


class Body(BaseModel):
    name: str

    execution_config: Annotated[
        SerializeAsAny[OptionalNullable[ExecutionConfig]],
        pydantic.Field(alias="executionConfig"),
    ] = UNSET

    @model_serializer(mode="wrap")
    def serialize_model(self, handler):
        optional_fields = set(["executionConfig"])
        nullable_fields = set(["executionConfig"])
        serialized = handler(self)
        m = {}

        for n, f in type(self).model_fields.items():
            k = f.alias or n
            val = serialized.get(k, serialized.get(n))
            is_nullable_and_explicitly_set = (
                k in nullable_fields
                and (self.__pydantic_fields_set__.intersection({n}))  # pylint: disable=no-member
            )

            if val != UNSET_SENTINEL:
                if (
                    val is not None
                    or k not in optional_fields
                    or is_nullable_and_explicitly_set
                ):
                    m[k] = val

        return m


try:
    Body.model_rebuild()
except NameError:
    pass


` // end of snapshot

	snaptest.DoTestSnapshot(t, snaptest.Options{
		Spec:         spec,
		GenYaml:      genYaml,
		IncludeGlobs: expectedSnapshotFiles,
		Expected:     expectedSnapshot,
	})
}
