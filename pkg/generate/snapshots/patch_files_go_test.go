func writeSnapshotPatch(t *testing.T, tempDir, relativePath string, pristine, patched []byte) {
	t.Helper()

	repoDir := t.TempDir()
	runGit(t, repoDir, "init", "-q")

	fullPath := filepath.Join(repoDir, filepath.FromSlash(relativePath))
	require.NoError(t, os.MkdirAll(filepath.Dir(fullPath), 0o755))
	require.NoError(t, os.WriteFile(fullPath, pristine, 0o644))
	runGit(t, repoDir, "add", "--", relativePath)
	runGit(t, repoDir, "-c", "user.name=Test", "-c", "user.email=test@example.com", "commit", "-qm", "init")

	require.NoError(t, os.WriteFile(fullPath, patched, 0o644))
	patchData := runGitAllowingExit1(t, repoDir, "diff", "--", relativePath)

	patchPath := patchfiles.PathFor(tempDir, relativePath)
	require.NoError(t, os.MkdirAll(filepath.Dir(patchPath), 0o755))
	require.NoError(t, os.WriteFile(patchPath, patchData, 0o644))
}

func runGit(t *testing.T, dir string, args ...string) []byte {
	t.Helper()

	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	output, err := cmd.CombinedOutput()
	require.NoError(t, err, string(output))
	return output
}

func runGitAllowingExit1(t *testing.T, dir string, args ...string) []byte {
	t.Helper()

	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	output, err := cmd.CombinedOutput()
	if err == nil {
		return output
	}

	var exitErr *exec.ExitError
	require.ErrorAs(t, err, &exitErr)
	require.Equal(t, 1, exitErr.ExitCode(), string(output))
	return output
}

