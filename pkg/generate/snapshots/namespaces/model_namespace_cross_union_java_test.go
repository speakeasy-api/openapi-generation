// modelNamespaceCrossUnionSpec spreads a discriminated oneOf and its members
// across model namespaces to exercise cross-namespace references selectively:
//   - the union lives in namespace `namespaceA`
//   - MemberA is co-located with the union (`namespaceA`) — a control that must stay
//     reference-free in both directions (no import for a same-namespace type)
//   - MemberB and MemberC each live in their own distinct namespace (`namespaceB`, `namespaceC`)
//
// This covers both directions and multi-namespace aggregation: each foreign
// member refers back to the union it belongs to, and the union's discriminator
// dispatch refers to the two foreign members (but not the co-located one).
// Guards against emitting the union and its members into separate namespaces
// without wiring up the references between them, and against over-referencing a
// same-namespace member.
