// Common spec with x-speakeasy-model-namespace using mixed casing that needs sanitization.
// The namespace "My_Custom_Namespace" should be sanitized per language conventions:
// - Go:         mycustomnamespace     (lowercase, no separators)
// - Python:     my_custom_namespace   (snake_case)
// - TypeScript: myCustomNamespace     (camelCase)
// - Ruby:       my_custom_namespace   (snake_case for files, PascalCase for modules)
const modelNamespaceSpec = `openapi: 3.1.0
info:
  title: Test
  version: "1.0"
servers:
  - url: https://api.example.com
paths:
  /widgets:
    get:
      operationId: listWidgets
      responses:
        "200":
          description: OK
          content:
            application/json:
              schema:
                $ref: "#/components/schemas/Widget"
components:
  schemas:
    Widget:
      type: object
      properties:
        name:
          type: string
      x-speakeasy-model-namespace: My_Custom_Namespace`

