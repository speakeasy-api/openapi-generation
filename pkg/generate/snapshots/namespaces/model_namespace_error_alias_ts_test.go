package namespaces

import (
	"testing"

	"github.com/speakeasy-api/openapi-generation/v2/pkg/generate/snapshots/snaptest"
)

// Regression test for model namespace collision and error alias conflict.
//
// The spec uses x-speakeasy-model-namespace on schemas referenced in both 200 and 401
// responses. The gen.yaml uses single-segment import paths (shared: "models") which
// previously caused namespace bucketing to produce inconsistent paths and duplicate
// import aliases in TypeScript.
func TestSnapTsModelNamespaceErrorAlias(t *testing.T) {
	t.Parallel()

	spec := `openapi: 3.1.0
info:
  title: Pet Store
  version: 1.0.0
servers:
  - url: https://api.example.com
paths:
  /dogs:
    get:
      operationId: listDogs
      responses:
        "200":
          description: OK
          content:
            application/json:
              schema:
                $ref: "#/components/schemas/dogs_Dog"
        "401":
          description: Unauthorized
          content:
            application/json:
              schema:
                $ref: "#/components/schemas/dogs_DogError"
components:
  schemas:
    dogs_Dog:
      type: object
      properties:
        name:
          type: string
        breed:
          $ref: "#/components/schemas/dogs_Breed"
      x-speakeasy-name-override: Dog
      x-speakeasy-model-namespace: dogs
    dogs_Breed:
      type: object
      properties:
        name:
          type: string
      x-speakeasy-name-override: Breed
      x-speakeasy-model-namespace: dogs
    dogs_DogError:
      type: object
      properties:
        message:
          type: string
      x-speakeasy-name-override: DogError
      x-speakeasy-model-namespace: dogs`

	// Pathological: single-segment "models" for shared, which previously made
	// path.Dir return "." and broke namespace bucket resolution.
	genYaml := `typescript:
  packageName: petstore
  imports:
    option: openapi
    paths:
      shared: models
      errors: models/errors
      operations: models/operations
      callbacks: models/callbacks
      webhooks: models/webhooks
`

	expectedSnapshotFiles := []string{
		"src/sdk/sdk.ts",
	}

	expectedSnapshot := `--- src/sdk/sdk.ts ---
/*
 * Code generated by Speakeasy (https://speakeasy.com). DO NOT EDIT.
 * Generated under the AGPL-3.0-only license.
 * SPDX-License-Identifier: AGPL-3.0-only
 */

import { listDogs } from "../funcs/list-dogs.js";
import { ClientSDK, RequestOptions } from "../lib/sdks.js";
import * as dogs from "../models/dogs/index.js";
import { unwrapAsync } from "../types/fp.js";

export class SDK extends ClientSDK {
  async listDogs(
    options?: RequestOptions,
  ): Promise<dogs.Dog> {
    return unwrapAsync(listDogs(
      this,
      options,
    ));
  }
}


` // end of snapshot

	snaptest.DoTestSnapshot(t, snaptest.Options{
		Spec:         spec,
		GenYaml:      genYaml,
		IncludeGlobs: expectedSnapshotFiles,
		Expected:     expectedSnapshot,
	})
}
