package snapshots

import (
	"testing"

	"github.com/speakeasy-api/openapi-generation/v2/pkg/generate/snapshots/snaptest"
)

func TestSnapGoItemSchema(t *testing.T) {
	t.Parallel()
	spec := `openapi: 3.1.0
info:
  title: Streaming API
  version: 1.0.0
paths:
  /logs:
    get:
      operationId: streamLogs
      responses:
        '200':
          description: A stream of log entries via json-seq
          content:
            application/json-seq:
              itemSchema:
                $ref: '#/components/schemas/LogEntry'
  /events:
    get:
      operationId: streamEvents
      responses:
        '200':
          description: A stream of events via JSONL with itemSchema
          content:
            application/jsonl:
              schema:
                description: The whole stream as text
                type: string
              itemSchema:
                $ref: '#/components/schemas/Event'
components:
  schemas:
    LogEntry:
      type: object
      required: [timestamp, message]
      properties:
        timestamp:
          type: string
          format: date-time
        message:
          type: string
        level:
          type: string
    Event:
      type: object
      required: [id, data]
      properties:
        id:
          type: string
        data:
          type: string`

	genYaml := `go:
  packageName: github.com/example/streaming
`

	expectedSnapshotFiles := []string{
		"models/components/event.go",
		"models/components/logentry.go",
	}

	expectedSnapshot := `--- models/components/event.go ---
// Code generated by Speakeasy (https://speakeasy.com). DO NOT EDIT.
// Generated under the AGPL-3.0-only license.
// SPDX-License-Identifier: AGPL-3.0-only

package components

type Event struct {
	ID   string ` + "`" + `json:"id"` + "`" + `
	Data string ` + "`" + `json:"data"` + "`" + `
}

func (e *Event) GetID() string {
	if e == nil {
		return ""
	}
	return e.ID
}

func (e *Event) GetData() string {
	if e == nil {
		return ""
	}
	return e.Data
}


--- models/components/logentry.go ---
// Code generated by Speakeasy (https://speakeasy.com). DO NOT EDIT.
// Generated under the AGPL-3.0-only license.
// SPDX-License-Identifier: AGPL-3.0-only

package components

import (
	"github.com/example/streaming/internal/utils"
	"time"
)

type LogEntry struct {
	Timestamp time.Time ` + "`" + `json:"timestamp"` + "`" + `
	Message   string    ` + "`" + `json:"message"` + "`" + `
	Level     *string   ` + "`" + `json:"level,omitzero"` + "`" + `
}

func (l LogEntry) MarshalJSON() ([]byte, error) {
	return utils.MarshalJSON(l, "", false)
}

func (l *LogEntry) UnmarshalJSON(data []byte) error {
	if err := utils.UnmarshalJSON(data, &l, "", false, nil); err != nil {
		return err
	}
	return nil
}

func (l *LogEntry) GetTimestamp() time.Time {
	if l == nil {
		return time.Time{}
	}
	return l.Timestamp
}

func (l *LogEntry) GetMessage() string {
	if l == nil {
		return ""
	}
	return l.Message
}

func (l *LogEntry) GetLevel() *string {
	if l == nil {
		return nil
	}
	return l.Level
}


` // end of snapshot

	snaptest.DoTestSnapshot(t, snaptest.Options{
		Spec:         spec,
		GenYaml:      genYaml,
		IncludeGlobs: expectedSnapshotFiles,
		Expected:     expectedSnapshot,
	})
}
