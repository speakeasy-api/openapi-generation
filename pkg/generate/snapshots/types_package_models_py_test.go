package snapshots

import (
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"

	"github.com/speakeasy-api/openapi-generation/v2/pkg/generate/snapshots/snaptest"
	"github.com/stretchr/testify/require"
)

// TestSnapPyTypesPackageModels verifies that when shared models are generated
// into the types package, its __init__.py exports every basemodel helper that
// the generated model serializers import from it.
func TestSnapPyTypesPackageModels(t *testing.T) {
	t.Parallel()

	spec := `openapi: 3.1.0
info:
  title: Types Package Models Test
  version: 1.0.0
servers:
  - url: https://api.example.com
paths:
  /widgets:
    post:
      operationId: createWidget
      requestBody:
        required: true
        content:
          application/json:
            schema:
              $ref: "#/components/schemas/Widget"
      responses:
        "200":
          description: OK
          content:
            application/json:
              schema:
                $ref: "#/components/schemas/Widget"
components:
  schemas:
    Widget:
      type: object
      required:
        - name
      properties:
        name:
          type: string
        description:
          type:
            - string
            - "null"
`

	genYaml := `python:
  packageName: testpkg
  imports:
    option: openapi
    paths:
      callbacks: ""
      errors: errors
      operations: ""
      shared: types
      webhooks: ""
`

	expectedSnapshotFiles := []string{
		"src/testpkg/types/__init__.py",
	}

	expectedSnapshot := `--- src/testpkg/types/__init__.py ---
"""Code generated by Speakeasy (https://speakeasy.com). DO NOT EDIT."""
# Generated under the AGPL-3.0-only license.
# SPDX-License-Identifier: AGPL-3.0-only

from .basemodel import (
    BaseModel,
    current_exclude_none,
    Nullable,
    OptionalNullable,
    UnrecognizedInt,
    UnrecognizedStr,
    UNSET,
    UNSET_SENTINEL,
    serialize_with_info,
)
from .base64fileinput import Base64EncodedString, Base64FileInput
from typing import Any, TYPE_CHECKING

from testpkg.utils.dynamic_imports import lazy_getattr, lazy_dir

if TYPE_CHECKING:
    from .widget import Widget, WidgetTypedDict

__all__ = [
    "Base64EncodedString",
    "Base64FileInput",
    "BaseModel",
    "Nullable",
    "OptionalNullable",
    "UNSET",
    "UNSET_SENTINEL",
    "UnrecognizedInt",
    "UnrecognizedStr",
    "Widget",
    "WidgetTypedDict",
    "current_exclude_none",
    "serialize_with_info",
]

_dynamic_imports: dict[str, str] = {
    "Widget": ".widget",
    "WidgetTypedDict": ".widget",
}


def __getattr__(attr_name: str) -> Any:
    return lazy_getattr(
        attr_name, package=__package__, dynamic_imports=_dynamic_imports
    )


def __dir__():
    return lazy_dir(dynamic_imports=_dynamic_imports)


` // end of snapshot

	snaptest.DoTestSnapshot(t, snaptest.Options{
		Spec:         spec,
		GenYaml:      genYaml,
		IncludeGlobs: expectedSnapshotFiles,
		Expected:     expectedSnapshot,
		AfterGenerate: func(t *testing.T, tempDir string) {
			t.Helper()
			// Type checkers accept any name imported from types because its
			// __init__.py defines a module-level __getattr__.
			typesDir := filepath.Join(tempDir, "src", "testpkg", "types")
			initSource, err := os.ReadFile(filepath.Join(typesDir, "__init__.py"))
			require.NoError(t, err)
			allBlock := regexp.MustCompile(`(?s)__all__ = \[(.*?)\]`).FindSubmatch(initSource)
			require.NotNil(t, allBlock)
			exported := map[string]bool{}
			for _, name := range regexp.MustCompile(`"(\w+)"`).FindAllSubmatch(allBlock[1], -1) {
				exported[string(name[1])] = true
			}

			modelSource, err := os.ReadFile(filepath.Join(typesDir, "widget.py"))
			require.NoError(t, err)
			importBlock := regexp.MustCompile(`(?s)from testpkg\.types import \((.*?)\)`).FindSubmatch(modelSource)
			require.NotNil(t, importBlock)
			for _, name := range strings.Split(string(importBlock[1]), ",") {
				if name = strings.TrimSpace(name); name != "" {
					require.True(t, exported[name], "types/__init__.py does not export %q imported by types/widget.py", name)
				}
			}
		},
	})
}
