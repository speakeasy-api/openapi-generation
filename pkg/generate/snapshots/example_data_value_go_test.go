package snapshots

import (
	"testing"

	"github.com/speakeasy-api/openapi-generation/v2/pkg/generate/snapshots/snaptest"
)

func TestSnapGoExampleDataValue(t *testing.T) {
	t.Parallel()
	spec := `openapi: 3.1.0
info:
  title: DataValue Examples API
  version: 1.0.0
servers:
  - url: https://api.example.com
paths:
  /items/{itemId}:
    get:
      operationId: getItem
      parameters:
        - name: itemId
          in: path
          required: true
          schema:
            type: string
          examples:
            example1:
              summary: A sample item ID
              dataValue: item-abc-123
      responses:
        '200':
          description: OK
          content:
            application/json:
              schema:
                $ref: '#/components/schemas/Item'
              examples:
                sampleItem:
                  summary: A sample item
                  dataValue:
                    id: item-abc-123
                    name: Widget
                    price: 9.99
components:
  schemas:
    Item:
      type: object
      required: [id, name, price]
      properties:
        id:
          type: string
        name:
          type: string
        price:
          type: number
          format: double`

	genYaml := `go:
  packageName: github.com/example/datavalue
`

	expectedSnapshotFiles := []string{
		"models/operations/getitem.go",
	}

	expectedSnapshot := `--- models/operations/getitem.go ---
// Code generated by Speakeasy (https://speakeasy.com). DO NOT EDIT.
// Generated under the AGPL-3.0-only license.
// SPDX-License-Identifier: AGPL-3.0-only

package operations

import (
	"github.com/example/datavalue/internal/utils"
	"github.com/example/datavalue/models/components"
)

type GetItemRequest struct {
	ItemID string ` + "`" + `pathParam:"style=simple,explode=false,name=itemId"` + "`" + `
}

func (g *GetItemRequest) GetItemID() string {
	if g == nil {
		return ""
	}
	return g.ItemID
}

type GetItemResponse struct {
	HTTPMeta components.HTTPMetadata ` + "`" + `json:"-"` + "`" + `
	// OK
	Item *components.Item
}

func (g GetItemResponse) MarshalJSON() ([]byte, error) {
	return utils.MarshalJSON(g, "", false)
}

func (g *GetItemResponse) UnmarshalJSON(data []byte) error {
	if err := utils.UnmarshalJSON(data, &g, "", false, nil); err != nil {
		return err
	}
	return nil
}

func (g *GetItemResponse) GetHTTPMeta() components.HTTPMetadata {
	if g == nil {
		return components.HTTPMetadata{}
	}
	return g.HTTPMeta
}

func (g *GetItemResponse) GetItem() *components.Item {
	if g == nil {
		return nil
	}
	return g.Item
}


` // end of snapshot

	snaptest.DoTestSnapshot(t, snaptest.Options{
		Spec:         spec,
		GenYaml:      genYaml,
		IncludeGlobs: expectedSnapshotFiles,
		Expected:     expectedSnapshot,
	})
}
