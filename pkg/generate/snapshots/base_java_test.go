package snapshots

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/speakeasy-api/openapi-generation/v2/pkg/generate/snapshots/snaptest"
	"github.com/stretchr/testify/require"
)

func TestSnapJavaBase(t *testing.T) {
	t.Parallel()
	spec := `openapi: 3.1.0
info:
  title: Pet API
  version: 1.0.0
paths:
  /pets:
    get:
      operationId: listPets
      responses:
        '200':
          description: OK
          content:
            application/json:
              schema:
                type: array
                items:
                  $ref: '#/components/schemas/Pet'
components:
  schemas:
    Pet:
      type: object
      required: [id, name]
      properties:
        id:
          type: integer
          format: int64
        name:
          type: string`

	// genYaml is partial and will be merged with target defaults
	genYaml := `java:
  groupId: com.example
  artifactId: petstore
`

	// expectedSnapshotFiles defines which generated files to include in the snapshot
	expectedSnapshotFiles := []string{
		"src/main/java/org/openapis/openapi/models/components/Pet.java",
	}

	expectedSnapshot := `--- src/main/java/org/openapis/openapi/models/components/Pet.java ---
/* 
 * Code generated by Speakeasy (https://speakeasy.com). DO NOT EDIT.
 * Generated under the AGPL-3.0-only license.
 * SPDX-License-Identifier: AGPL-3.0-only
 */
package org.openapis.openapi.models.components;

import com.fasterxml.jackson.annotation.JsonCreator;
import com.fasterxml.jackson.annotation.JsonProperty;
import jakarta.annotation.Nonnull;
import java.lang.Override;
import java.lang.String;
import java.util.Optional;
import org.openapis.openapi.utils.Utils;


public class Pet {

    @JsonProperty("id")
    private long id;


    @JsonProperty("name")
    private String name;

    @JsonCreator
    public Pet(
            @JsonProperty("id") long id,
            @JsonProperty("name") @Nonnull String name) {
        this.id = id;
        this.name = Optional.ofNullable(name)
            .orElseThrow(() -> new IllegalArgumentException("name cannot be null"));
    }

    public long id() {
        return this.id;
    }

    public String name() {
        return this.name;
    }

    public static Builder builder() {
        return new Builder();
    }


    public Pet withId(long id) {
        this.id = id;
        return this;
    }


    public Pet withName(@Nonnull String name) {
        this.name = Utils.checkNotNull(name, "name");
        return this;
    }


    @Override
    public boolean equals(java.lang.Object o) {
        if (this == o) {
            return true;
        }
        if (o == null || getClass() != o.getClass()) {
            return false;
        }
        Pet other = (Pet) o;
        return 
            Utils.enhancedDeepEquals(this.id, other.id) &&
            Utils.enhancedDeepEquals(this.name, other.name);
    }
    
    @Override
    public int hashCode() {
        return Utils.enhancedHash(
            id, name);
    }
    
    @Override
    public String toString() {
        return Utils.toString(Pet.class,
                "id", id,
                "name", name);
    }

    @SuppressWarnings("UnusedReturnValue")
    public final static class Builder {

        private long id;

        private String name;

        private Builder() {
          // force use of static builder() method
        }

        public Builder id(long id) {
            this.id = id;
            return this;
        }

        public Builder name(@Nonnull String name) {
            this.name = Utils.checkNotNull(name, "name");
            return this;
        }

        public Pet build() {
            return new Pet(
                id, name);
        }

    }
}


` // end of snapshot

	snaptest.DoTestSnapshot(t, snaptest.Options{
		Spec:         spec,
		GenYaml:      genYaml,
		IncludeGlobs: expectedSnapshotFiles,
		Expected:     expectedSnapshot,
		// When no nullable field is defined org.openapitools:jackson-databind-nullable
		// (JsonNullable) must not be added as a dependency in build.gradle.
		AfterGenerate: func(t *testing.T, tempDir string) {
			t.Helper()
			buildGradle, err := os.ReadFile(filepath.Join(tempDir, "build.gradle"))
			require.NoError(t, err)
			require.NotContains(t, string(buildGradle), "jackson-databind-nullable",
				"JsonNullable dependency must be absent when no field is nullable")
		},
	})
}
