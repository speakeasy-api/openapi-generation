func TestAddWithIDDuplicateID(t *testing.T) {
	store := New()

	data1 := map[string]interface{}{"name": "John Doe"}
	data2 := map[string]interface{}{"name": "Jane Doe"}
	customID := "duplicate-id"

	// Add first entry
	err := store.AddWithID(customID, data1)
	if err != nil {
		t.Fatalf("First AddWithID() returned error: %v", err)
	}

	// Try to add second entry with same ID
	err = store.AddWithID(customID, data2)
	if err == nil {
		t.Fatal("AddWithID() should return error for duplicate ID")
	}

	if err.Error() != "entry with ID duplicate-id already exists" {
		t.Fatalf("Expected error 'entry with ID duplicate-id already exists', got %v", err)
	}

	// Verify only first entry exists
	if len(store.Data) != 1 {
		t.Fatalf("Expected 1 entry, got %d", len(store.Data))
	}

	storedData := store.Data[customID]
	if storedData["name"] != "John Doe" {
		t.Fatalf("Expected name 'John Doe', got %v", storedData["name"])
	}
}

func TestAddWithIDMixedWithAutoGenerated(t *testing.T) {
	store := New()

	// Add data with custom ID
	customData := map[string]interface{}{"name": "Custom User"}
	customID := "custom-123"
	err := store.AddWithID(customID, customData)
	if err != nil {
		t.Fatalf("AddWithID() returned error: %v", err)
	}

	// Add data with auto-generated ID
	autoData := map[string]interface{}{"name": "Auto User"}
	autoID, err := store.Add(autoData)
	if err != nil {
		t.Fatalf("Add() returned error: %v", err)
	}

	// Verify both entries exist
	if len(store.Data) != 2 {
		t.Fatalf("Expected 2 entries, got %d", len(store.Data))
	}

	// Verify custom ID entry
	customStored, exists := store.Data[customID]
	if !exists {
		t.Fatal("Custom ID entry not found")
	}
	if customStored["name"] != "Custom User" {
		t.Fatalf("Expected custom name 'Custom User', got %v", customStored["name"])
	}

	// Verify auto-generated ID entry
	autoStored, exists := store.Data[autoID]
	if !exists {
		t.Fatal("Auto-generated ID entry not found")
	}
	if autoStored["name"] != "Auto User" {
		t.Fatalf("Expected auto name 'Auto User', got %v", autoStored["name"])
	}

	// Verify IDs are different
	if customID == autoID {
		t.Fatal("Custom ID and auto-generated ID should be different")
	}
}

func TestAddWithIDConcurrent(t *testing.T) {
	store := New()
	const numGoroutines = 50

	// Channel to collect results
	results := make(chan struct {
		id   string
		err  error
		data map[string]interface{}
	}, numGoroutines)

	// Launch concurrent goroutines with custom IDs
	for i := 0; i < numGoroutines; i++ {
		go func(index int) {
			customID := fmt.Sprintf("concurrent-%d", index)
			data := map[string]interface{}{
				"index": index,
				"data":  "concurrent test",
			}

			err := store.AddWithID(customID, data)
			results <- struct {
				id   string
				err  error
				data map[string]interface{}
			}{customID, err, data}
		}(i)
	}

	// Collect all results
	collectedIDs := make(map[string]bool)
	collectedData := make(map[string]map[string]interface{})

	for i := 0; i < numGoroutines; i++ {
		result := <-results

		if result.err != nil {
			t.Fatalf("Goroutine %d returned error: %v", i, result.err)
		}

		if result.id == "" {
			t.Fatalf("Goroutine %d returned empty ID", i)
		}

		// Check for duplicate IDs
		if collectedIDs[result.id] {
			t.Fatalf("Duplicate ID generated: %s", result.id)
		}

		collectedIDs[result.id] = true
		collectedData[result.id] = result.data
	}

	// Verify all data was stored correctly
	if len(store.Data) != numGoroutines {
		t.Fatalf("Expected %d entries, got %d", numGoroutines, len(store.Data))
	}

	// Verify each stored entry matches the collected data
	for id, expectedData := range collectedData {
		storedData, exists := store.Data[id]
		if !exists {
			t.Fatalf("Data not found for ID: %s", id)
		}

		if storedData["index"] != expectedData["index"] {
			t.Fatalf("Data mismatch for ID %s: expected index %v, got %v",
				id, expectedData["index"], storedData["index"])
		}
	}
}
